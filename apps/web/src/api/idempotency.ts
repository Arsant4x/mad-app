/**
 * ⚖️ **مفتاحُ الطلب الواحد** (توجيه ٢٧٦ · ق-١٦٠٩/ب): يُولَّد مرّةً لكلِّ نافذةِ مستند (سندُ قبض · سندُ صرف · قبضُ إيجار) ويُرسل في رأس
 * `Idempotency-Key` مع كلِّ محاولةِ حفظٍ منها — فنقرةٌ مزدوجة أو إعادةٌ بعد مهلةٍ لم يصل جوابُها تعيد المستندَ نفسَه ولا تكتب ثانياً.
 */
export const newRequestKey = (): string => crypto.randomUUID();

/** خيارُ الطلب الذي يحمل الرأس — فارغٌ حين لا مفتاح. */
export const withRequestKey = (key?: string) => (key ? { headers: { 'Idempotency-Key': key } } : {});
