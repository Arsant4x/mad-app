import { runShardedJest } from './sharded-jest.mjs';

/**
 * ⭐ **خطوةُ الـ`e2e` في السير — مُشرَّحة** (`ق-٤٢٣` · `ق-٤٢٤`).
 *
 * **العطل مقيسٌ بشاهدٍ لا بحجّة**: `٩٩` مجموعةً في عمليةٍ واحدة بلا سقفٍ
 * معلَن — **والخطوةُ على الحافّة**:
 *
 *   · `main` بلا إضافة ⇒ **خضراء ×٥** (والخطوة `٣:١٦`).
 *   · طلبٌ بسكربتاتٍ واختبارِ وحدة ⇒ **أخضر**.
 *   · طلبٌ **بمجموعةِ `e2e` واحدة جديدة** ⇒ **أحمر**.
 *   · وطلبُ كاشفِ المعاملات ⇒ **أحمر ×٣** (والخطوة `٣:٤٩` **تنهار قرب نهايتها**).
 *
 * ⚠️ **والانهيارُ قرب النهاية لا في أوّلها** — **وهو ما يميّز الإشباعَ من
 * الانفجار**: تراكمٌ يبلغ السقف، لا عطلٌ يقع من أول مجموعة.
 *
 * ⚠️ **وثلاثةُ قياساتٍ برّأت الكاشف**: `٢٠٠٬٠٠٠` نداءٍ و`٣٬٠٠٠` معاملةٍ حقيقية
 * بكنسٍ صريح ⇒ **صفر**؛ وثمانُ مجموعات `e2e` بـ`--logHeapUsage` ⇒ **لا زيادة**.
 * ⇒ **فالعلّةُ الخطوةُ لا ما يُضاف إليها.**
 *
 * ── ولماذا لا يُرفع السقفُ وحده ──────────────────────────────────────────
 *
 * **السقفُ يؤجّل والتشريحُ يُغلق** (`ق-٤١١`): محلّياً **٦٢ ثم انقطاع** بالسقف
 * المخفوض، **و١٧٦ بصفر سقوط** بالتشريح. **فالاثنان معاً، ومنزلتُهما مختلفة.**
 */
const SHARDS = Number(process.env.E2E_SHARDS ?? 4);

const { verdict, verdicts, fileCount, shardCount } = await runShardedJest({
  // ⚠️ **الوسائطُ نفسُها التي كانت في `test:e2e`** — **فالمقيسُ هو التشريحُ
  //    وحده**، ولا يختلط به تغييرُ نطاق.
  jestArgs: '--testPathPattern=e2e-spec --forceExit --runInBand',
  shards: SHARDS,
  label: 'اختبارات التكامل',
});

if (verdict === 'NO_MATCH') {
  console.error('\n✘ لا مجموعةَ `e2e` واحدة تطابق — وصفرُ اختبارٍ ليس نجاحاً.');
  process.exit(1);
}

console.log(`\n▶ ملفّاتُ e2e على القرص: ${fileCount} · شرائح: ${shardCount}`);

if (verdict === 'INTERRUPTED') {
  // 🔴 **انقطاعٌ لا نتيجة**: لا حصيلةَ لشريحة، فلا يُنسب شيءٌ إلى الشيفرة.
  console.error('\n⛔ انقطاع — شريحةٌ لم تكمل، فلا حكمَ على الشيفرة (ق-٤٠٢).');
  console.error(`  أحكامُ الشرائح: ${verdicts.join(' · ')}`);
  console.error('  اقرأ سببَ الانقطاع قبل أن تنسبه — ونفادُ الذاكرة يُقرأ في المخرَج أعلاه.');
  process.exit(2);
}
if (verdict === 'EMPTY') {
  console.error('\n✘ لم يركض توكيدٌ واحد في إحدى الشرائح — فخضرةٌ بلا تشغيلٍ ليست نجاحاً.');
  process.exit(1);
}
if (verdict === 'FAIL') {
  console.error('\n✘ سقطت مجموعةٌ — اقرأ المخرَج أعلاه.');
  process.exit(1);
}

console.log('\n✔ اختبارات التكامل خضراء على كل الشرائح.');
