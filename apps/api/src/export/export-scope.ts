/** اسم مندوب Prisma من اسم النموذج — `BusinessActivity` ⇒ `businessActivity`. */
export function delegateName(model: string): string {
  return model[0].toLowerCase() + model.slice(1);
}

/** كل نموذج يحمل `companyId`، مقروءاً من المخطط وقت التشغيل. */
export function tenantOwnedModels(): string[] {
  return Prisma.dmmf.datamodel.models
    .filter((m) => m.fields.some((f) => f.name === 'companyId'))
    .map((m) => m.name);
}

/**
 * النماذج التي تُصدَّر فعلاً.
 *
 * ⚠️ **ويُفحص الاستثناء في الاتجاهين.** اسمٌ في `EXPORT_EXCLUSIONS` لا يقابله
 * نموذج (خطأٌ مطبعي · نموذجٌ أُعيدت تسميته) **يُسقط الإقلاع** — وإلا لصار
 * الاستثناء ميتاً بصمت، فيُصدَّر ما ظننّا أننا منعناه. وهو الوجه المقابل تماماً
 * لنموذجٍ جديد بلا قرار.
 */
export function exportedModels(): string[] {
  const owned = tenantOwnedModels();
  const unknown = Object.keys(EXPORT_EXCLUSIONS).filter((name) => !owned.includes(name));
  if (unknown.length > 0) {
    throw new Error(
      `EXPORT_EXCLUSIONS يسمّي نماذج لا وجود لها أو لا تحمل companyId: ${unknown.join(', ')} — ` +
        'استثناءٌ ميت يُسرّب ما ظُنّ أنه مُنع.',
    );
  }
  return owned.filter((name) => !(name in EXPORT_EXCLUSIONS));
}
