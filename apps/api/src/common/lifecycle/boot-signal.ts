/**
 * **إيقافٌ في أثناء الإقلاع** (`ق-١٥٢٣`) — يُسجَّل **عند تحميل هذا الملفّ**، وهو أوّلُ ما يستورده `main.ts`.
 *
 * الخادمُ هو العمليةُ الأولى في الحاوية، **والعمليةُ الأولى بلا مستمعٍ تُهمل النواةُ إشارتَها**. فقِيس خطُّ الإقلاع كلُّه:
 *   • مستمعٌ في أوّل `bootstrap()` لا يكفي — **الاستيراداتُ تُحمَّل قبلها** (Nest وشجرةُ الوحدات): إشارةٌ فيها ⟸
 *     `31537 ms` ثم قتلٌ `137`. فالتسجيلُ هنا، في أوّل استيراد، قبل الثقيل كلِّه.
 *   • و**يبقى حتى `listen`** ثم يُرفع (في `main.ts`) — مستمعُ Nest قبل `listen` أغلق التطبيقَ ثم فُتح منفذُه فبقيت
 *     العمليةُ حتى قُتلت (`30812 ms` · `137`).
 *
 * **ولا طلبَ يُخدم قبل الاستماع**، فلا شيءَ يُفرَغ: يُخرج فوراً بـ`0`، وما كان في منتصف معاملةٍ تُرجعه القاعدة.
 * ⚠️ **وحدُّه معلَن**: بين `exec` وتحميل هذا الملفّ بدءُ node نفسِه (قبل أيّ شيفرةٍ لنا) — نافذةٌ لا يبلغها مستمع.
 */
export function exitDuringBoot(signal: NodeJS.Signals): void {
  // eslint-disable-next-line no-console
  console.log(`إيقافٌ في أثناء الإقلاع (${signal}): لم يُخدم طلبٌ بعد، فيُخرج الآن`);
  process.exit(0);
}

process.once('SIGTERM', exitDuringBoot);
process.once('SIGINT', exitDuringBoot);
