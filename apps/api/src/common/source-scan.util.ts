import { readdirSync, statSync } from 'fs';
import { join } from 'path';

/**
 * **أدواتُ الحرّاس المشتقّة — مصدرٌ واحد** (`ق-٣٢٨`).
 *
 * ── العطلُ الذي أنشأ هذا الملف ────────────────────────────────────────────
 *
 * كان `stripComments` منسوخاً في حارسٍ آخر، **وفيه خطأٌ صامت**: بدأ نمطُ
 * التعليق السطريّ بـ`^` ثم `\s` مكرّرة — **و`\s` تبتلع السطر الجديد**،
 * فتُلتهم الأسطرُ الفارغة قبل كل تعليق. القياس:
 * `contracts.service.ts` **٩٩٣ سطراً تصير ٩٠٨**، **فيُبلَّغ عن العطل في السطر
 * ٨٩١ وهو في ٩٧٣** — انحرافُ ٨٢ سطراً.
 *
 * ⚠️ **ولا يظهر ما دام الحارسُ أخضر**: رقمُ السطر لا يُقرأ إلا **لحظةَ سقوط
 * الحزمة** — أي حين يكون أشدَّ ما يُحتاج إليه. **فوُضع في مصدرٍ واحدٍ يُثبَت
 * برقمِ سطرٍ معلوم**، لا في نسختين تُصلَح إحداهما.
 */

/**
 * الكود بلا تعليقاته — **والأسطرُ محفوظةٌ عدداً** كي يصدق رقمُ السطر.
 *
 * ⚠️ **`[^\S\r\n]*` لا `\s*`**: الأولى مسافةٌ أفقيّة وحدها، **والثانية تبتلع
 * السطرَ الجديد** فتُزيح كلَّ ما بعدها.
 */
export const stripComments = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, '')).replace(/^[^\S\r\n]*\/\/.*$/gm, '');

/**
 * الكود بلا تعليقاته **وبلا نصوصه** — **والسطرُ والعمودُ محفوظان** (`ق-٣٤٩`).
 *
 * ⚠️ **العطلُ الذي أضافها**: `live-guard-precheck` كان يبحث عن `new
 * PrismaClient(` في **نصّ الملف**، **فأدان مثالاً مكتوباً داخل سلسلةٍ نصّية**
 * في مُكتشِفِ حارسٍ آخر. **ومثالُ الكسر في الاختبار ليس كسراً في الشيفرة** —
 * وهو عينُ ما أوجب `ق-٣٣١`: **الحارسُ يقرأ الكود لا النصّ**.
 *
 * **والمحذوفُ يُملأ فراغاً** (لا يُحذف) — الصياغةُ المُثبَتة في
 * `no-silent-skip` منذ نشأته: فيبقى السطرُ والعمودُ صادقَين.
 */
export const stripCommentsAndStrings = (s: string): string => {
  const blank = (m: string) => m.replace(/[^\n]/g, ' ');
  return s
    .replace(/\/\*[\s\S]*?\*\//g, blank)
    .replace(/\/\/[^\n]*/g, blank)
    .replace(/`(?:\\.|[^`\\])*`/g, blank)
    .replace(/'(?:\\.|[^'\\\n])*'/g, blank)
    .replace(/"(?:\\.|[^"\\\n])*"/g, blank);
};

/** كل ملفات `.ts` تحت الجذر — بلا اختبارات وبلا تعريفات. */
export function sourceFiles(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (name === 'node_modules' || name === 'dist') continue;
    if (statSync(full).isDirectory()) sourceFiles(full, out);
    else if (/\.ts$/.test(name) && !/\.spec\.ts$|\.d\.ts$/.test(name)) out.push(full);
  }
  return out;
}
