/** هل يُستبعَد هذا المفتاح من `details`؟ — بالاسم كما يصل في جسم الطلب، بلا حساسيةٍ لحالة الأحرف. */
export function isRedactedKey(key: string): boolean {
  return REDACTED_FIELD_NAMES.has(key.toLowerCase());
}
