import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * حارسُ رأس القواعد — `docs/decisions.md` للقرارات وحدَها (`ق-١٦٤٤` · بوّابتُه بحكم `ق-١٦٤٥`/٤).
 *
 * بنصّ صاحب المشروع: «ما ليس قرارًا لا يدخله أبدًا، ومكانُه ملفُّ الوقائع»، و«فلا صفَّ «توجيه
 * الجلسة» ولا صفَّ «نتائج توجيه» بعد اليوم». وكان التذكيرُ وحدَه قائماً (القاعدة ٢٧)، فهذا
 * الحارسُ يُسقط الحزمةَ على صفٍّ في السجلّ **رقمُه بعد `ق-١٦٤٤`** وعنوانُه من الصنفين:
 *
 *   «توجيه الجلسة» · «نتائج توجيه» أو «نتائج التوجيه» · أو عنوانٌ يبدأ بـ«توجيه» ورقمِه
 *
 * والحركاتُ تُنزع قبل المطابقة، فـ«توجيهُ الجلسة» و«نتائجُ توجيه» صنفٌ واحد مع غير المشكول.
 *
 * ## حدُّه المعلَن
 *
 * - ما قبل `ق-١٦٤٥` لا يُفحص: بقيت فيه صفوفٌ مختلطةٌ بحكم صاحب المشروع (`ق-١٦٤٥`/٢)، ومنها `ق-١٦١٢`.
 * - يقرأ العنوانَ وحدَه: صفُّ مهمّةٍ بعنوانٍ آخر لا يراه؛ فالاختبارُ الثالث في رأس القواعد يبقى
 *   حكمَ الكاتب، وهذا يمسك الصنفين اللذين سمّاهما صاحبُ المشروع بأسمائهما.
 */

const REPO = join(__dirname, '..', '..', '..', '..');
const LAST_BEFORE_RULE = 1644;

const toLatin = (s: string) => s.replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)));
/** الحركاتُ العربية والتطويل تُنزع، فالمشكولُ وغيرُه نصٌّ واحد. */
const bare = (s: string) => s.replace(/[ً-ْـ]/g, '');

// والصنفُ الثالث في **أوّل** العنوان وحدَه: قرارٌ صحيح يذكر «(توجيه ٢٧٨)» في وسطه لا يُصاب.
const TASK_TITLE = /توجيه الجلسة|نتائج (ال)?توجيه|^توجيه\s+[0-9٠-٩]/;

export interface Row {
  id: number;
  title: string;
}

/** صفوفُ السجلّ: الخليةُ الأولى تعريضٌ يبدأ برقم القرار، والعنوانُ ما بعد الشَّرطة الطويلة. */
export function registryRows(markdown: string): Row[] {
  const rows: Row[] = [];
  for (const line of markdown.split(/\r?\n/)) {
    if (!line.startsWith('|')) continue;
    const cell = line.split('|')[1] ?? '';
    const m = cell.match(/\*\*[^*]*?ق-([0-9٠-٩]+)\s*—\s*([^*]+)\*\*/);
    if (!m) continue;
    rows.push({ id: Number(toLatin(m[1])), title: bare(m[2]).trim() });
  }
  return rows;
}

export function taskRowsAfterRule(markdown: string): string[] {
  return registryRows(markdown)
    .filter((r) => r.id > LAST_BEFORE_RULE && TASK_TITLE.test(r.title))
    .map((r) => `ق-${r.id} — ${r.title}`);
}

describe('رأسُ القواعد — لا صفَّ «توجيه الجلسة» ولا «نتائج توجيه» بعد ق-١٦٤٤', () => {
  const decisions = readFileSync(join(REPO, 'docs', 'decisions.md'), 'utf8');

  it('السطحُ غير فارغ، ويرى صفّاً بعد ق-١٦٤٤ — وإلا فالحارسُ يفحص العدم', () => {
    const rows = registryRows(decisions);
    expect(rows.length).toBeGreaterThanOrEqual(1000);
    expect(rows.some((r) => r.id > LAST_BEFORE_RULE)).toBe(true);
    // والصفُّ القائم بالعنوان المحظور قبل القاعدة يُرى، فالمسبارُ يقرأ العناوين.
    expect(rows.some((r) => r.id === 1612 && TASK_TITLE.test(r.title))).toBe(true);
  });

  it('⭐ لا صفَّ مهمّةٍ بعنوانه في السجلّ بعد ق-١٦٤٤', () => {
    expect(taskRowsAfterRule(decisions)).toEqual([]);
  });

  // ⭐ الإثباتُ العكسيّ مبنيٌّ في الحارس: حالاتٌ يجب أن تُصاب وأخرى يجب ألّا تُصاب.
  it('الكاشف يمسك ما يجب ويترك ما يجب — مُثبَتٌ بحالات', () => {
    const sample = [
      '| **▶️ ق-١٦٥٠ — توجيهُ الجلسة ٢٩٠: أحكامٌ ثم البناء** | x | y | ▶️ |',
      '| **✅ ق-١٦٥١ — نتائجُ توجيه ٢٩٠** | x | y | ✅ |',
      '| **ق-1652 — نتائج التوجيه الأخير** | x | y | ✅ |',
      '| **ق-١٦٥٣ — توجيه ٢٩١: دليلُ الجهاز** | x | y | ▶️ |',
      '| **⚖️ ق-١٦٥٤ — أحكامُ صاحب المشروع على تقرير ٢٩٠** | x | y | ⚖️ |',
      '| **⚖️ ق-١٦٥٥ — حارسٌ يُبنى مع أوّل توجيهٍ يمسّه** | x | y | ⚖️ |',
      '| **⚖️ ق-١٦٥٦ — سلّمُ «الحالة» ثابتٌ (توجيه ٢٨١)** | x | y | ⚖️ |',
      '| **▶️ ق-١٦١٢ — توجيهُ الجلسة ٢٧٧: قبل القاعدة** | x | y | ▶️ |',
    ].join('\n');
    expect(taskRowsAfterRule(sample).map((s) => s.split(' — ')[0])).toEqual(['ق-1650', 'ق-1651', 'ق-1652', 'ق-1653']);
  });
});
