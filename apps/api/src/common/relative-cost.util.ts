/**
 * **كلفةٌ نسبيّةٌ إلى مرجعٍ في التشغيل نفسه** (`ق-٤٨٨`).
 *
 * ── العلّة ────────────────────────────────────────────────────────────────
 *
 * تأكيدُ زمنٍ بسقفٍ مطلق (`< 100` م.ث) **يصدق على جهازٍ فارغ ويكذب تحت الحِمل**:
 * **مقيسٌ (2026-09-10)** — البصمةُ **2.7 م.ث** وحدَها، **و1719 م.ث** حين شُغّلت
 * مع خمسٍ وثلاثين مجموعة. **فالتأكيدُ سقط بلا تدهورٍ واحد في الشيفرة.**
 *
 * ── ولماذا لا يُوسَّع الحدُّ ولا يُعزَل القياس ──────────────────────────────
 *
 * **كلاهما يقتل الغرضَ بطريقةٍ مختلفة** (حكمُ المالك): **التوسيعُ يجعله لا يمسك
 * تدهوراً حقيقياً**، **والعزلُ يجعله لا يُشغَّل في السير**.
 *
 * ⇒ **فيُقاس ما ندّعيه فعلاً**: **أن العملية رخيصةٌ نسبةً إلى ما حولها** — لا
 * أنها تحت رقمٍ صادقٍ على جهازٍ فارغ.
 *
 * ── الشروطُ الثلاثة (أمرُ المالك) ────────────────────────────────────────
 *
 *   ① **المرجعُ من الجنس نفسه ويُقاس في التشغيل عينه** — لا رقمٌ محفوظٌ من
 *      تشغيلٍ سابق، فمحفوظٌ يعود إلى السقف المطلق من بابٍ آخر.
 *   ② **والنسبةُ تُعلَن رقماً** عند موضع استعمالها — لا «معقولة».
 *   ③ **ومُثبَتةٌ بالعكس**: عمليةٌ أُبطئت عمداً **تُسقط التأكيد** — **فنسبةٌ لا
 *      تمسك تدهوراً نسبةٌ عمياء**.
 *
 * ── حدُّه المعلَن ─────────────────────────────────────────────────────────
 *
 * ⚠️ **يقيس التدهورَ النسبيَّ لا المطلق**: **بطءٌ عامٌّ في المضيف يمرّ — وهو
 * مقصود**. فمن أراد سقفاً مطلقاً للمضيف نفسِه يقيسه في مكانٍ آخر.
 *
 * ⚠️ **والتناوبُ لا التتابع**: يُشغَّل الموضوعُ والمرجعُ بالتناوب، **فحِملٌ
 * يتغيّر في منتصف القياس يمسّهما معاً** — وقياسٌ متتابع يُحمّل أحدَهما وحده.
 */
export interface RelativeCost {
  /** متوسّطُ الموضوع بالملّي ثانية. */
  subjectMs: number;
  /** ومتوسّطُ المرجع. */
  referenceMs: number;
  /** الموضوعُ ÷ المرجع — **وهو وحده ما يُحكَم عليه**. */
  ratio: number;
  rounds: number;
}

const ms = (from: bigint) => Number(process.hrtime.bigint() - from) / 1e6;

export function relativeCost(subject: () => unknown, reference: () => unknown, rounds = 10): RelativeCost {
  // إحماءٌ للاثنين معاً: أوّلُ تشغيلٍ يحمل كلفةَ التهيئة وقراءةِ القرص أوّلَ
  // مرّة، **وهي ليست موضوعَ القياس**.
  subject();
  reference();

  let subjectTotal = 0;
  let referenceTotal = 0;
  for (let i = 0; i < rounds; i++) {
    const s = process.hrtime.bigint();
    subject();
    subjectTotal += ms(s);

    const r = process.hrtime.bigint();
    reference();
    referenceTotal += ms(r);
  }

  const subjectMs = subjectTotal / rounds;
  const referenceMs = referenceTotal / rounds;
  return {
    subjectMs,
    referenceMs,
    // مرجعٌ بلا زمنٍ يُقاس عليه يجعل النسبةَ لا نهائية — **ويُعلَن كذلك بدل
    // أن يُقسَم على صفرٍ فيُقرأ `NaN` نجاحاً**.
    ratio: referenceMs > 0 ? subjectMs / referenceMs : Number.POSITIVE_INFINITY,
    rounds,
  };
}
