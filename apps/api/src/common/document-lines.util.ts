/**
 * ⚖️ **ترتيبُ سطور المستند معلَنٌ لا مصادَف** (`ق-١٤١٢` · مكسورُ اليوم ب في التوجيه ٢٦٣).
 *
 * ── العطل المقيس ─────────────────────────────────────────────────────────
 *
 * سطورُ الفاتورة والعرض كانت تُقرأ **بلا ترتيب** (`lines: true`)، فيعيدها Postgres **بترتيبها على القرص**
 * — وهو يتبدّل بما يُحذف ويُكتب حولها. ولا عمودَ كان يحمل الترتيب: `createdAt` واحدٌ لسطور المستند كلِّها
 * (بدايةُ المعاملة) و`id` عشوائيّ. **فأسقط اختبارَ الخصم متقطّعاً** (`line-discount ③`: الإشعارُ الدائن
 * `[0,20]` بدل `[20,0]`) — **والأثرُ على التاجر لا على الاختبار**: فاتورةٌ تُعرض بترتيبٍ وتُطبع بآخر،
 * و`cbc:ID` في المستند المختوم يُكتب بترتيب القراءة.
 *
 * ── الحكم ────────────────────────────────────────────────────────────────
 *
 * **① رقمُ السطر يُكتب من ترتيب الإدخال** — `numberLines` في كلِّ إنشاء (`1..n` بلا فجوة)، والعمودُ بلا
 * افتراضٍ في القاعدة فإنشاءٌ ينساه يسقط بصوت، ومكرَّرُه يردّه فريدُ `(المستند، رقم السطر)`.
 * **② وكلُّ قراءةٍ لسطور مستندٍ مرقَّمة تمرّ بـ`LINE_ORDER`** — وحارسُ `document-line-order.spec.ts` يقرأ
 * الشجرةَ ويُسقط الحزمة على قراءةٍ بلا ترتيب، **مشتقّاً من المخطَّط** (كلُّ نموذجٍ يحمل `lineNo`).
 *
 * ⚠️ **ولا يُعالَج التذبذبُ بغيره** (نصُّ التوجيه): لا ترتيبَ في الاختبار ولا مهلة — الترتيبُ في المستند.
 */
export const LINE_ORDER = { orderBy: { lineNo: 'asc' } } as const;

/** يرقّم السطورَ بترتيب إدخالها `1..n` — الموضعُ الوحيد الذي يُكتب فيه رقمُ السطر. */
export function numberLines<T extends object>(rows: readonly T[]): (T & { lineNo: number })[] {
  return rows.map((row, i) => ({ ...row, lineNo: i + 1 }));
}
