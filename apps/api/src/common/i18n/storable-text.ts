import { resolveMessage } from './messages';

/**
 * ⚖️ **مصدرٌ واحد لكلّ نصٍّ يأتي من جهةٍ خارجية ويُكتب في عمودٍ نصّي** (`ق-٩٨٢`/١).
 *
 * عمودُ النصّ في القاعدة **يرفض البايتَ الصفريّ** (`22021`). فنصٌّ يأتي من الخارج — جوابُ الهيئة ·
 * رسالةُ خطأٍ رماها `fetch` · معرّفٌ تُعيده الهيئة — إن حمل ذلك البايت أسقط الكتابةَ كلَّها:
 * **فيضيع الردُّ** (لا يُكتب `REJECTED` والمستندُ يبقى «مختومٌ بانتظار الإبلاغ» وقد رُدّ)،
 * **ويُكتب نصُّ خطأ `Prisma` كاملاً في صفّ التاجر** بمسار الملفّ وسطوره — تسريبٌ داخليٌّ لا عطلُ
 * ترميز — **والتاجرُ يقرأ ما لا معنى له** حيث يتوقّع سببَ الردّ. وقبلها (`ق-٩٧١`): رسائلُ
 * `formatMessage` تحمل مفتاحاً وفاصلاً صفريّاً ومعامِلات، فكانت كتابةُ `lastError` تسقط ومعها
 * دورةُ الطابور للمنشأة كلِّها.
 *
 * فكلُّ كتابةٍ لعمودٍ معلَنٍ في المخطَّط بـ`/// @external-text` تمرّ من هنا **وحدَه** — يحرسه
 * `common/external-text-storable.spec.ts` المشتقُّ من ذلك الإعلان، فالموضعُ الخامس لا يُنسى.
 *
 * ⛔ **ولا يُطبَّق على ما يُدخله المستخدم عند الحدّ** (`ق-٩٨١`): بايتٌ صفريٌّ في اسم عميلٍ
 * مُدخَلٌ فاسدٌ **يُردّ بصوت** (`500` ولا صفّ) — وتنقيتُه تقبل ما يجب أن يُرفض.
 */

/** الحدُّ الذي كانت المواضعُ تقصّ عنده كلٌّ على حدة — ٥٠٠ حرف، صار هنا وحدَه. */
export const STORABLE_TEXT_MAX = 500;

// البايتُ الصفريّ يُسمّى بالرمز لا يُكتب حرفاً — حرفٌ صفريّ في المصدر يجعل الملفَّ ثنائياً عند git (`ق-٩٧٤`).
const NUL = String.fromCharCode(0);

/**
 * نصٌّ خارجيٌّ صالحٌ للتخزين: بلا بايتٍ صفريّ، ومقصوصٌ عند الحدّ. `null`/`undefined` تبقى `null`
 * (عمودٌ اختياريّ يُصفَّر)، والرقمُ يصير نصّاً (معرّفُ الهيئة يأتي رقماً أحياناً).
 *
 * والحدُّ يُمرَّر صراحةً لمستندٍ لا يُقصّ (`ق-١٥٠٦`: النسخةُ المجازة من الهيئة — `Infinity`)؛ ومستندٌ كذاك
 * يُرفض قبلها إن حمل البايتَ الصفريّ، فلا تُعدّله هنا بحرف.
 */
export function storableText(raw: string | number, max?: number): string;
export function storableText(raw: string | number | null | undefined, max?: number): string | null;
export function storableText(raw: string | number | null | undefined, max: number = STORABLE_TEXT_MAX): string | null {
  if (raw === null || raw === undefined) return null;
  return String(raw).split(NUL).join('').slice(0, max);
}

/**
 * سببٌ مرميٌّ يُخزَّن ويُقرأ: يُحلّ إلى نصّه العربيّ أولاً (رسائلُ `formatMessage` مفتاحٌ وفاصلٌ
 * صفريٌّ ومعامِلات — يحلّها مُرشِّح الاستثناءات للشاشة، وهنا للقاعدة)، ثم يُنقّى ويُقصّ.
 */
export function storableError(e: unknown): string {
  const raw = e instanceof Error ? e.message : String(e);
  return storableText(resolveMessage(raw, 'ar'));
}
