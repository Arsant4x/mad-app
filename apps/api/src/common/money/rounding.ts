/**
 * سياسة التدوير المركزية — **المكان الوحيد** الذي يُدوَّر فيه رقم في المنصّة.
 *
 * ## العطل الذي تعالجه
 *
 * قبل هذا الملف كان في الخادم **أربعة تعريفات منفصلة** للدالة نفسها —
 * `invoices.service.ts` · `opening-balance.util.ts` · `payments.service.ts` ·
 * `reports.service.ts` — كلها `Math.round(n * 100) / 100` مكتوبةً من جديد.
 * وأربع نسخ من قاعدة واحدة تعني أن تصحيح إحداها **يترك ثلاثاً خاطئة**.
 *
 * ⚠️ **والتدوير المبعثر هو مصدر فروق الإقرارات الضريبية الأول** — لأن الفرق
 * لا يظهر في اختبار، بل في مجموعٍ شهري يخالف مجموعاً آخر بهللات.
 *
 * ## جدول المقاييس — مربوطٌ بالمخطَّط لا مستقلٌّ عنه
 *
 * كل سياق هنا يقابل دقّةَ عمودٍ في `schema.prisma`، وحارسٌ يفحص تطابقهما في
 * الاتجاهين. فمن وسّع عموداً ونسي السياسة يسقط، ومن غيّر السياسة ونسي العمود
 * يسقط كذلك — وهي الحالة التي لا يكشفها اختبارٌ سلوكي لأن كليهما «يعمل».
 *
 * ## ولماذا الكمية ثلاثة أرقام
 *
 * الصيدلية تبيع بالحبة، والصالون يقيس بالمليلتر، والمحطة باللتر. ورقمان
 * عشريان **يقرّبان ذلك عند الإدخال** — لا عند العرض. فالخسارة تقع في القاعدة
 * ولا تُسترجع.
 */

/**
 * ⚠️ **تُقرأ هذه الأسماء من `unified-build-plan.md` (ق-٦) لا من اجتهاد.**
 * وثلاثة منها تعطي ٢ اليوم — **وليست تكراراً**: فصلُها هو ما يسمح بتغيير
 * تدوير الضريبة وحدها غداً دون أن يتحرك تدوير سطر الفاتورة معها.
 */
export const SCALE = {
  /** مبلغ سطر — `Decimal(18,2)` */
  LINE_AMOUNT: 2,
  /** إجمالي مستند — `Decimal(18,2)` */
  INVOICE_TOTAL: 2,
  /** مبلغ ضريبة — `Decimal(18,2)` */
  VAT_AMOUNT: 2,
  /** كمية — `Decimal(18,3)` */
  DERIVED_QUANTITY: 3,
  /** سعر وحدة صافياً — `Decimal(18,6)` */
  UNIT_PRICE: 6,
  /** تكلفة وحدة — `Decimal(18,6)` */
  UNIT_COST: 6,
} as const;

export type RoundingContext = keyof typeof SCALE;

/**
 * التدوير الوحيد المسموح.
 *
 * ## ⚠️ سلوكه اليوم = سلوك التعريفات الأربعة التي حلّ محلّها — **عمداً**
 *
 * هذه الموجة تُوحّد **مكان** التدوير ولا تغيّر **نتيجته**. وفيه عيبان معروفان
 * مثبَّتان في `rounding.spec.ts` بتوكيدات موسومة، ولكلٍّ بندٌ مسجَّل:
 *
 * **① حدّ IEEE-754.** `1.005 * 100` يساوي `100.49999999999999`، فيدوَّر
 *    نزولاً إلى `1.00` والصواب `1.01`.
 *
 * **② عدم التناظر حول الصفر.** `Math.round(-100.5)` يساوي `-100`: النصف
 *    يُقرَّب نحو `+∞` لا بعيداً عن الصفر. فالفاتورة تحصّل `1.01` والإشعار
 *    الدائن يردّ `1.00` — نصف هللة تبقى وتتراكم على كل مرتجع.
 *
 * **ولماذا لا يُصلَحان هنا:** الإصلاح يغيّر ناتج المال. و`zatca/ubl/
 * invoice-xml.util.ts` يدوّر بـ`Math.round` الخام في موضعين — فإصلاح الدفتر
 * وحده **يجعل المستند المختوم يخالف الدفتر**، وهو أسوأ من العيب نفسه.
 * فالإصلاح الصحيح كنسةٌ واحدة تشمل كل مواضع التدوير، وهي موجتها لا هذه.
 */
export function roundTo(value: number, context: RoundingContext): number {
  const factor = 10 ** SCALE[context];
  return Math.round(value * factor) / factor;
}

/**
 * اختصارٌ للمبالغ — يبقى لأن ستةً وستين موضعاً تناديه، ونقلُها دفعةً واحدة
 * تغييرٌ واسع بلا عائد. **والسلوك الآن واحد لأن التعريف واحد**، وهو الغرض.
 */
export const round2 = (value: number): number => roundTo(value, 'LINE_AMOUNT');
