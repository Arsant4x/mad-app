/**
 * سنةُ بادئة رقم المستند — **من تاريخ المستند، لا من ساعة الخادم**.
 *
 * ## العطل الذي عالجته
 *
 * كانت المولّدات الخمسة تقرأ `new Date().getFullYear()`. والمعيار المُعلَن في
 * الشيفرة نفسها هو **تقويم العميل المحلي** (`create-credit-note.dto.ts`:
 * «The client's local calendar date. Server time is UTC and the column is a
 * DATE»)، و`issueDate` **إلزامي من العميل**. فينشأ انفصالٌ **قائمٌ اليوم**:
 *
 *   اللحظة 2026-12-31T22:00:00Z · الخادم UTC (كما هو منشور فعلاً)
 *   متصفّح التاجر (الرياض) يرسل  issueDate = "2027-01-01"
 *   والخادم يحسب                  getFullYear() = 2026
 *   ⟵ INV-2026-XXXX على فاتورةٍ تاريخها 2027 — ثلاث ساعات كل ٣١ ديسمبر.
 *
 * وأثره **يُخزَّن في رقم مستند** فلا يُصحَّح بتبديل عرض. ولا يعالجه ضبط `TZ`
 * وحده: `TZ=Asia/Riyadh` يُصلح هذه الحالة ويكسر عكسها — تاجرٌ في منطقةٍ أخرى.
 * **فالمصدر الصحيح تاريخُ المستند نفسه، لا منطقةٌ يُتّفق عليها.**
 *
 * ## لماذا `UTC` هنا
 *
 * أعمدة التواريخ من نوع `@db.Date`، وسلسلةُ `YYYY-MM-DD` تُحلَّل **UTC حصراً**
 * بالمواصفة. فقراءةُ السنة بـ`getUTCFullYear` تُطابق ما خزّنته القاعدة، بينما
 * `getFullYear` تُعيد إدخال منطقة العملية من الباب الخلفي.
 *
 * ⚠️ **وحدُّها معلَن:** تحلّ مصدرَ السنة، ولا تحلّ **التأريخ الرجعي** — فاتورةٌ
 * تُنشأ في 2027 بتاريخ 2026 ستأخذ رقماً في تسلسل 2026 بعد انتهائه. وذاك قرار
 * سياسة مسجَّل بلا بدء، لا عطلٌ في هذه الدالة.
 */
export function documentYear(date: Date): number {
  return date.getUTCFullYear();
}
