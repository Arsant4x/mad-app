import { SetMetadata } from '@nestjs/common';

export const ALLOW_WHILE_CONSENT_PENDING_KEY = 'allowWhileConsentPending';

/**
 * ثقوبُ بوّابة الموافقة على المعالجين الفرعيين (`ق-٥٨٩`).
 *
 * ⭐ **والحكمُ «اختيارٌ لا حجب»**: «الخدمةُ صارت تقتضي هذا — **فاقبل، أو خذ بياناتك
 * واخرج**». ⇒ **فأمام التاجر بابان لا باب**، وهذه العلامةُ هي البابُ الثاني:
 *
 *   · **قراءةُ الاتفاقية وقبولُها** — وإلا كانت بوّابةً لا مخرجَ منها.
 *   · **التصديرُ** — «نزّل بياناتك» ليست وعداً في نصٍّ بل مسارٌ يعمل وهو ممنوع.
 *   · **طلبُ الإغلاق وسحبُه** — «أغلق حسابي» كذلك.
 *   · **الإشعاراتُ** — فبها يعرف لماذا مُنع، ومنها وصله التذكير.
 *
 * ⛔ **ولا تُوضَع على قراءةِ بياناتٍ ولا على أيّ كتابة**: من لم يأذن بالمعالج الفرعيّ
 * **لا تمرّ بياناتُه به** — وكلُّ عملٍ في المنصّة يمرّ بأحدهم. **فالثقبُ للخروج لا للبقاء.**
 */
export const AllowWhileConsentPending = () => SetMetadata(ALLOW_WHILE_CONSENT_PENDING_KEY, true);
