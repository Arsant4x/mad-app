import { AsyncLocalStorage } from 'node:async_hooks';

/**
 * ⭐ **كاشفُ المعاملة المتداخلة — يُبلّغ ولا يُسقط** (`ق-٣٦٢` · `ق-٣٩٢`).
 *
 * ── العطل الذي بُني له ───────────────────────────────────────────────────
 *
 * `PosService.ring` يفتح معاملة، ثم يُنادي `zatcaQrFor` من داخلها **ففتحت
 * ثانية**. ⇒ **كلُّ بيعةٍ طائرة تمسك اتصالاً وتطلب ثانياً**، **وثلاثُ بيعاتٍ
 * متزامنة تطلب ستةً وتمسك ثلاثة** — فإن كان المجموعُ دونها **وقع تجويعٌ تامّ
 * وتوقّف الكاشير عند الذروة** (`ق-٣٥٩`).
 *
 * ⚠️ **والعدُّ الساكن سقط مرّتين في هذا السؤال بعينه**: مجسٌّ أعطى **٣ وكلُّها
 * سليمة ولم يجد العطل**، وثانٍ متعدٍّ أعطى **٠ والحالةُ قائمة** (`ق-٣٦١`).
 * **فالكاشفُ الحيّ هو العدّاد** — وما يُبلّغ عنه تحت الحزمة **هو الرقم**.
 *
 * ── الشروط الستّة ────────────────────────────────────────────────────────
 *
 * **① الإبلاغُ يحمل أثرَ النداء كاملاً** لا اسمَ الدالّة — «فمن يقرؤه بعد
 *    أسبوع يحتاج المسار لا الموضع».
 * **② ومهلةُ التحويل إلى إسقاط معلَنة**: **بعد أول حزمةٍ نظيفةٍ بصفر بلاغ**،
 *    لا بعد أول تنظيف — «فتنظيفٌ واحد قد يترك ما لم يُشغَّل بعد».
 * **③ ولا يُسقط ولا يُبطئ**: المسارُ المعتاد **قراءةٌ واحدة** من الحالة
 *    الجارية (`getStore`)، **ولا يُلتقط الأثرُ إلا عند التداخل** — وهو نادر.
 * **④ ويُبلَّغ مرّةً لكل موضعٍ لا لكل نداء** — وإلا أغرق السجلّ.
 * **⑤ والكلفةُ تُقاس على المسار الحيّ** لا في العزل.
 * **⑥ والمفتاحُ من إطارِ النداء لا من إطار الكاشف** — ⚠️ **وإلا صار المفتاحُ
 *    واحداً للجميع، فبُلِّغ عن موضعٍ وأُخفي الباقي**.
 */
const active = new AsyncLocalStorage<true>();

/**
 * الآثارُ المتمايزةُ التي بُلِّغ عنها (`ق-٣٩٤`).
 *
 * ⚠️ **والشرطُ الأصليّ كان «مرّةً لكل موضع» — وسُحب بحجّته**: المفتاحُ من
 * الأثر **لا يحمل موضعَ المستدعي بعد التحويل غير المتزامن** (`ق-٣٩٥`)،
 * **فأعطى مفتاحين لموضعٍ واحد**. **والغرضُ كان «ألّا يُغرق السجلّ» لا
 * «مفتاحاً من الأثر»** — فبقي الغرضُ وسقطت الوسيلة.
 *
 * ⚠️ **وثمنُه معلَن**: **قد يُبلَّغ عن الموضع الواحد أكثرَ من مرّة** —
 * **والحدُّ يمنع الإغراق لا التكرار**. **فمن يقرأ البلاغات يعدّ الأثرَ
 * المتمايز لا عدد الأسطر.**
 */
const reported = new Set<string>();

/** **حدُّ البلاغات — رقمٌ مُعلَنٌ لا افتراض** (حكمُ المالك): يكفي لسطحٍ متوسط ولا يُغرق. */
export const NESTED_REPORT_LIMIT = 50;

/**
 * إطاراتٌ تُتخطّى لبلوغ **موضع النداء** (الشرط ⑥): ملفُّ الكاشف وخدمتُه،
 * **وداخليّاتُ `node` ومكتباتُه**.
 *
 * ⚠️ **وأُضيفت الداخليّاتُ بعد إثباتٍ عكسيّ**: أوّلُ صياغةٍ أعطت المفتاحَ
 * `at AsyncLocalStorage.run (node:internal/...)` **ثم `<غير معروف>` للنداء
 * نفسه** — **فمفتاحان لموضعٍ واحد**، وهو نقيضُ الشرط ④.
 */
const OWN_FRAMES = /nested-transaction-probe|tenant-prisma\.service|node:internal|node_modules/;

/**
 * ⚠️ **وحدُّ الأثر يُرفع عند الالتقاط وحده**: `Error.stackTraceLimit` افتراضُه
 * **عشرة إطارات**، **تستهلكها آليّةُ التزامن قبل أن تصل إطاراتُ المستدعي** —
 * فيعود المفتاحُ داخليّاً أو مجهولاً. **ولا كلفةَ على المسار المعتاد**: لا
 * يُلتقط أثرٌ أصلاً إلا عند التداخل.
 */
const CAPTURE_FRAMES = 60;

function captureStack(): string {
  const previous = Error.stackTraceLimit;
  Error.stackTraceLimit = CAPTURE_FRAMES;
  const stack = new Error().stack ?? '';
  Error.stackTraceLimit = previous;
  return stack;
}

/**
 * أوّلُ إطارٍ **خارج** الكاشف وخدمته — **وهو موضعُ النداء**.
 *
 * ⚠️ **الشرط ⑥ بعينه**: لو أُخذ الإطارُ الأول مطلقاً لكان **دائماً هذا الملفّ**،
 * فيصير المفتاحُ واحداً ويُبلَّغ عن موضعٍ واحدٍ مهما تعدّدت المواضع.
 */
export function callSiteOf(stack: string): string {
  for (const line of stack.split('\n').slice(1)) {
    const frame = line.trim();
    if (!frame.startsWith('at ')) continue;
    if (OWN_FRAMES.test(frame)) continue;
    return frame;
  }
  return '<موضعٌ غير معروف>';
}

/** ما بُلِّغ عنه في هذا التشغيل — تقرؤه الحزمة، **فما تُبلّغ عنه هو الرقم**. */
export function nestedTransactionReports(): string[] {
  return [...reported];
}

/** يُفرَّغ بين المجموعات — فعدُّ مجموعةٍ لا يرث عدَّ سابقتها. */
export function resetNestedTransactionReports(): void {
  reported.clear();
}

/**
 * يُشغّل `work` داخل سياقٍ يُعلن «معاملةٌ جارية»، **ويُبلّغ إن كانت واحدةٌ
 * جاريةً أصلاً**.
 *
 * ⚠️ **يُبلّغ ولا يُسقط** (الشرط ②): **القياسُ أولاً ثم المنع** — فإسقاطٌ قبل
 * أن يُعرف السطحُ يُوقف مساراتٍ لم تُفحص بعد.
 */
export async function withTransactionProbe<T>(work: () => Promise<T>): Promise<T> {
  if (active.getStore()) {
    // ⚠️ **ولا يُلتقط الأثرُ إلا هنا** (الشرط ③): المسارُ المعتاد قراءةٌ واحدة.
    const stack = captureStack();
    if (!reported.has(stack) && reported.size < NESTED_REPORT_LIMIT) {
      reported.add(stack);
      // ① **الأثرُ كاملاً** — فالمسارُ هو ما يُحتاج بعد أسبوع لا الموضع،
      //    **وبلاغٌ بأثرٍ مبتور لا يُنتفَع به**.
      console.warn(`⚠️ معاملةٌ داخل معاملة (ق-٣٦٢) — بلاغٌ ${reported.size}/${NESTED_REPORT_LIMIT}\n${stack}`);
    }
  }
  return active.run(true, work);
}
