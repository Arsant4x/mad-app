/**
 * نافذةُ إعادة الفتح (`ق-٥٤٨` · `ق-٥٥٩`): بعد إغلاق الحساب بطلب التاجر يُقبل طلبُ إعادة الفتح
 * هذه المدّةَ — **وبانقضائها يُمحى غيرُ الملزِم آلياً**، فلا عودةَ بعدها. وهي **رقمٌ واحد** مع
 * نافذة النسخة لمنشأةٍ بلا حركة (`ARCHIVE_WINDOW_DAYS`): أجلُ العودة هو أجلُ النسخة هو أجلُ المحو.
 *
 * تعيش هنا لا في وحدة الطلبات لأن حارسَ المستأجر يقرأها ليقولها في رسالة المغلق —
 * **تُعلَن ولا تُخفى**.
 */
export const REOPEN_WINDOW_DAYS = 90;

/** آخرُ يومٍ تُقبل فيه إعادةُ الفتح — من الإغلاق. */
export function reopenUntil(closedAt: Date): Date {
  return new Date(closedAt.getTime() + REOPEN_WINDOW_DAYS * 24 * 3600 * 1000);
}
