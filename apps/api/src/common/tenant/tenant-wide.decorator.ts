import { SetMetadata } from '@nestjs/common';

export const TENANT_WIDE_KEY = 'tenantWide';

/**
 * **مسارٌ مفتوحٌ لكلّ فاعلٍ في المنشأة — بإعلانٍ وسبب** (`ق-١١٩٨`/①).
 *
 * `TenantGuard` **مغلقٌ افتراضياً**: مسارٌ لا يُعلن شاشتَه (`@RequiresScreen`) ولا
 * صاحبَه (`@OwnerOnly`) ولا يفتح نفسَه هنا **يُرفض** — كوضع الدعم (`@SupportShell`).
 * فكان متحكّمٌ بلا وسمٍ يمرّ بكلّ موظّفٍ إلى خدمته، والحمايةُ الوحيدة أن تتذكّر
 * الخدمةُ `assertIsCompanyOwner` — وهو ما لا يُتذكَّر في المتحكّم الثامن.
 *
 * **السببُ إلزاميٌّ ويُقرأ في موضعه**: منتقياتٌ يحتاجها كلُّ فاعل (العملات · الفروع)،
 * أو حالٌ يُعرض لكلّ من دخل (الموافقةُ · الإغلاق). **ومن فتح به مساراً يكتب** فتح
 * باباً بيده — والسببُ بجواره ليُراجَع؛ وحارسٌ ساكن (`tenant-guard-declared.spec`)
 * يوجب سبباً لا يقصر عن حدّه ويحصي المواضع كلَّ تشغيل.
 */
export const TenantWide = (reason: string) => SetMetadata(TENANT_WIDE_KEY, reason);
