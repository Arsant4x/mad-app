import { SetMetadata } from '@nestjs/common';

export const SUPPORT_SHELL_KEY = 'supportShell';

/**
 * **مسارٌ يجوز لوضع الدعم قراءتُه بلا شاشةٍ في نطاق الإذن** (`ق-٥٢٧`).
 *
 * وضعُ الدعم **مغلقٌ افتراضياً**: مسارٌ لا يُعلن شاشتَه (`@RequiresScreen`) لا
 * يُقرأ فيه — **فما لا يُسمّى لا يُطلب في الإذن ولا يراه المالكُ قبل موافقته**.
 * والاستثناءُ الوحيد ما يُعيد **هويّةَ السائل نفسِه أو صلاحياتِه** — لا صفّاً من
 * بيانات المنشأة — كـ`GET /me/permissions` الذي ترسم به الواجهةُ أزرارَها.
 *
 * ⚠️ **يُعلَن على المسار لا في قائمةٍ داخل الحارس** — كنمط «بلا أبٍ»: الاستثناءُ
 * بسببه في موضعه، والحارسُ يقرؤه. **ومن وضعه على مسارٍ يُعيد بياناتِ منشأةٍ
 * فتح باباً جانبياً بيده** — والسببُ مكتوبٌ بجواره ليُراجَع.
 */
export const SupportShell = () => SetMetadata(SUPPORT_SHELL_KEY, true);
