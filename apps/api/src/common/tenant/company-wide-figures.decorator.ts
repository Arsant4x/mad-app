import { SetMetadata } from '@nestjs/common';

export const COMPANY_WIDE_FIGURES_KEY = 'companyWideFigures';

/**
 * ⚖️ **مسارٌ رقمُه رقمُ المنشأة كلِّها — لمن يرى فروعَها كلَّها** (توجيه ٢٧٥ · `ق-١٥٨١`، بحكم صاحب المشروع).
 *
 * «**الأرقامُ المجمَّعة على مستوى المنشأة (أرصدةُ الحسابات وملخّصُها · الإقرار · ملخّصاتُ العميل والمورّد · ما لم يُبلَّغ للهيئة ·
 * سجلُّ التدقيق) تُرفض للمقيَّد كالقوائم المالية**». فكان كلٌّ منها يُعلن «على مستوى المنشأة بحقّها» ويُقرأ لموظّفٍ مقيَّدٍ بفرع
 * (مسحُ توجيه ٢٧٤، الكتلة ٥ج). والقوائمُ المالية تحرس نفسَها في خدمتها (`assertWholeCompanyReader`)؛ وهذا الوسمُ يقول الشيءَ
 * نفسَه على المسار، **فيرفضه `TenantGuard` قبل الخدمة** ولا يُنسى في خدمةٍ تاسعة.
 *
 * **والسببُ إلزاميٌّ ويُقرأ في موضعه**: ما الرقمُ الذي يجمع المنشأةَ كلَّها. والمالكُ ومن وُسم بـ`allBranches` يقرؤه؛ ومقيَّدٌ
 * بفروعٍ (أو بلا فرعٍ مسنَد) يُردّ 403 مسمّى السبب ودالّاً على أرقام فروعه.
 */
export const CompanyWideFigures = (reason: string) => SetMetadata(COMPANY_WIDE_FIGURES_KEY, reason);
