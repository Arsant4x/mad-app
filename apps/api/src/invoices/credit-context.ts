/**
 * ⭐ **ما يجب أن يُصرَّح به عند كل إنشاء فاتورة** (`ق-٣٣٨` · `ق-٣٣٩` · `ق-٣٤٠`).
 *
 * ── لماذا يُصرَّح ولا يُستنتج ────────────────────────────────────────────
 *
 * **حكمُ المالك**: «**البوّابةُ تفحص ما يُفتح ذمّةً لا ما يُسدَّد في المعاملة
 * نفسها**» — «**وحدٌّ يمنع بيعاً نقدياً عطلٌ يصنعه لا يمنعه**». وشرطُه:
 * «**فإن تعذّر معرفةُ ذلك عند الفحص، أعلنه ولا تلتفّ**».
 *
 * ⚠️ **وقد تعذّر — مقيساً لا مرجَّحاً، فيُعلَن هنا**: `PosService.ring` يُنشئ
 * الفاتورة بـ`invoicesService.create` **ثم يُنشئ سندَها في `runInTenantContext`
 * تالية** — **معاملتان لا واحدة**، وتعليقُ الشيفرة نفسُه يقولها: «outside the
 * block above because it opens its own tenant transaction». **فعند لحظة الفحص
 * لا تحمل الفاتورةُ ولا قاعدةُ البيانات شيئاً يميّز المسدَّدَ فوراً** —
 * والسندُ لم يوجد بعد.
 *
 * **والبدائلُ التي فُحصت وسقطت**:
 *
 * - **`dueDate === issueDate`**: بيعٌ آجلٌ يستحقّ اليوم يحمل الشكلَ نفسه —
 *   **فيُنتج تصنيفاً كاذباً يعيش في البيانات**، وهو ما رفضه `ق-٣٣٨` نصّاً.
 * - **`posShiftId` غيرُ فارغ**: يُقرأ من الفاتورة بعد إنشائها لا قبله،
 *   **وبيعُ الكاشير الآجل (على حساب العميل) يحمله أيضاً**.
 * - **الفحصُ بعد السند**: يقع في معاملةٍ أخرى بعد أن صارت الفاتورةُ أمراً
 *   واقعاً — **فيصير تقريراً لا بوّابة**.
 *
 * ⇒ **فالوحيدُ الذي يعرف هو المستدعي**، ويُصرّح. **والمواضعُ ثلاثة لا مئتان**
 * (الفاتورةُ المباشرة · تحويلُ عرض السعر · بيعُ الكاشير)، **فحجّةُ `ق-٣٤٨`
 * — «وسيطٌ يُنسى في التاسع والستين بعد المئتين» — لا تقوم هنا**؛ وحارسٌ
 * مشتقّ يُدين أيَّ مستدعٍ رابعٍ لا يصرّح.
 *
 * ── ⚠️ والثغرةُ الباقية تُعلَن ولا يُلتفّ عليها ─────────────────────────
 *
 * **التصريحُ نيّةٌ لا ضمانة**: إن سقطت معاملةُ السند بعد نجاح معاملة
 * الفاتورة، **بقيت فاتورةُ كاشيرٍ مفتوحةً غيرَ مسدَّدة وقد أعفيت من الحدّ**.
 * **وأثرُه محدودٌ ومقيس**: بيعةٌ واحدة، **ويظهر تعرّضُها في الفحص التالي
 * فيُصحَّح نفسَه** — بخلاف منعِ البيع النقديّ الذي يُعطّل الكاشير عند الذروة.
 */
export type InvoiceSettlement =
  /** **تفتح ذمّةً** — فتُفحص على الحدّ. */
  | 'ON_ACCOUNT'
  /**
   * **تُسدَّد فورَ إنشائها** — فلا تُفحص (`ق-٣٣٨`).
   *
   * ⚠️ **ولا يُصرَّح بها إلا مسارٌ يُنشئ سندَها في نفس الطلب** — وهو الكاشير
   * وحده اليوم.
   */
  | 'IMMEDIATE';

/** الفاعلُ الذي يُنسب إليه التجاوز — **اسمُه وقتَ الفعل لا معرّفُه وحده**. */
export interface CreditActor {
  id: string;
  actorType: string;
  name: string;
}

export interface CreditContext {
  /** ⚠️ **لا افتراضَ له** — يُصرَّح في كل مستدعٍ، وحارسٌ يُدين من لا يصرّح. */
  settlement: InvoiceSettlement;
  /** من ينشئ الفاتورة — يُنسب إليه التجاوزُ إن وقع. `null` لمسارٍ بلا فاعل. */
  actor: CreditActor | null;
  /** **صرّح الطلبُ بالتجاوز** (`creditOverride` في المدخل) — نيّةٌ لا إذن. */
  overrideRequested: boolean;
  /**
   * **ويملك `invoice:review`** — **مقروءاً من `PermissionsService.forActor`**،
   * وهو عينُ ما تقرؤه الواجهة، **لا حسابٌ محلّيّ ثانٍ يفترق عنه**.
   */
  canOverride: boolean;
}

