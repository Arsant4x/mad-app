import { Prisma } from '@mad-app/db';
import { getOrCreateAccount } from './inventory-accounts.util';

/**
 * ⚖️ **حسابُ ما دُفع نيابةً عن المستأجرين** (السؤالان ٥١ و٤١٣ · `ق-١٦٠٠` · `ق-١٦٠٩`/د، بحكم صاحب المشروع).
 *
 * ## ما هو
 *
 * المؤجّرُ يدفع فاتورةَ مرفقٍ **عن** المستأجر ثم يستردّها منه بشروط «المبالغ المدفوعة نيابةً» الخمسة (دليلُ الوكلاء §8.1:
 * أوّلُها أن يكون المستأجرُ متلقّي الخدمة، وآخرُها فصلُ التكلفة في المستندات): **ليس إيراداً ولا عليه ضريبة** — بل ذمّةٌ
 * على المستأجر بقدر ما دُفع عنه. فالدفعُ يُقيَّد مديناً هنا والمطالبةُ أو الخصمُ من التأمين دائناً، ويبقى الرصيدُ ما دُفع
 * ولم يُستردّ بعد.
 *
 * ## ولماذا `1260` لا `1250`
 *
 * `1250` «ضريبة القيمة المضافة — مدخلات» في الدليل. و`1260` خارجَ كلِّ نطاقٍ يُولَّد منه رمز (`code-bands.ts`)، **ويُنشأ عند
 * أوّل حاجة** للمنشآت القائمة ويدخل دليلَ المولود الجديد — كحسابَي عقار التشغيل (`owner-rent-accounts.util.ts`).
 *
 * ⚠️ **حدٌّ معلَن**: ما دفعه المؤجّرُ عن المستأجر قبل هذا الحساب سُجّل مصروفاً أو في حسابٍ آخر، فاستردادُه الآن يُنقص `1260`
 * دون مقابلٍ فيه — والرصيدُ السالبُ هنا علامةٌ على ذلك يُطابقها المحاسب، لا عطلٌ يُصحَّح آليّاً.
 */
export const ON_BEHALF_ACCOUNT_CODE = '1260';
export const ON_BEHALF_ACCOUNT_NAME = 'مبالغ مدفوعة نيابةً عن المستأجرين';

export const getOrCreateOnBehalfAccount = (tx: Prisma.TransactionClient, companyId: string) =>
  getOrCreateAccount(tx, companyId, ON_BEHALF_ACCOUNT_CODE, ON_BEHALF_ACCOUNT_NAME, 'asset');
