import { Prisma } from '@mad-app/db';
import { getOrCreateAccount } from './inventory-accounts.util';

/**
 * حسابُ الإيراد المؤجَّل — `2400`.
 *
 * ## ما هو
 *
 * **التزامٌ عن خدمةٍ قُبض ثمنُها ولم تُقدَّم بعد.** فقبضُ إيجارِ شهرٍ لم يبدأ
 * **ليس إيراداً** — هو دَينُ خدمةٍ على المنشأة، يتحوّل إيراداً **شهراً بشهر**
 * كلّما قُدِّمت (`IFRS 15`).
 *
 * ## ولماذا رمزٌ ثابتٌ لا مشتقّ بـ`MAX+1` (`ق-٤٧٠`)
 *
 * `code-bands.ts` وُضع **لحساباتٍ كثيرةٍ من نوعٍ واحد**: بنكٌ لكلّ بنك، ودرجٌ
 * لكلّ درج. **وهذا حسابٌ واحدٌ لكلّ منشأة** ككلِّ `2200` و`2300` و`5800`.
 *
 * ⭐ **والعلّةُ الحاسمة**: `resolveAccountIds` **يقرأ الحسابَ برمزه** — ورمزٌ
 * يختلف بين المنشآت **لا يُقرأ برمز**، فيوجب جدولَ أدوارٍ لا وجودَ له.
 *
 * **والمقيس** (2026-09-10): أعلى رمزِ خصومٍ في **١٣٣ دليلاً** هو `2300`،
 * **و`2400` حرٌّ في كلِّها** — صفرُ منشأةٍ تستعمله.
 *
 * ## ولماذا يُنشأ عند الحاجة لا في الدليل وحده (`ق-٤٧١`)
 *
 * 🔴 `resolveAccountIds` يعيد `null` **تخطّياً صامتاً** حين ينقص رمز — **لا
 * يُكتب القيدُ ولا يُبلَّغ أحد**. فإضافةُ `2400` إلى الدليل الافتراضي وحده
 * تعني أن **كلَّ منشأةٍ قائمة يسقط تحويلُها بلا رسالة**.
 *
 * فيُضاف إلى الدليل **للمنشآت الجديدة**، ويُنشأ **عند أوّل تحوّلٍ** للقائمة —
 * نفس نمط `5800` و`1300` و`1250` و`3900`.
 */
export const DEFERRED_REVENUE_ACCOUNT_CODE = '2400';
export const DEFERRED_REVENUE_ACCOUNT_NAME = 'إيرادات مؤجَّلة';

export const getOrCreateDeferredRevenueAccount = (tx: Prisma.TransactionClient, companyId: string) =>
  getOrCreateAccount(tx, companyId, DEFERRED_REVENUE_ACCOUNT_CODE, DEFERRED_REVENUE_ACCOUNT_NAME, 'liability');
