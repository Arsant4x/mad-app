/**
 * ينشئ الحسابات الناقصة لمنشأة داخل معاملة قائمة.
 *
 * `skipDuplicates` هو كل الحيلة: يجعل الاستدعاء **عديم الأثر عند التكرار**
 * دون قراءة سابقة ولا حلقة upsert — الفهرس الفريد (companyId, code) يحسم،
 * فالحساب الموجود لا يُلمس اسمه ولا نوعه ولا رصيده مهما تكرر الاستدعاء.
 *
 * يتطلب أن يكون `app.company_id` مضبوطاً على المعاملة (سياسة RLS تفحص
 * الإدراج أيضاً عبر WITH CHECK) — لذلك تضبطه كل نقطة استدعاء قبل النداء.
 *
 * @returns عدد الصفوف المنشأة فعلاً (0 = الدليل كان مكتملاً).
 */
export async function createDefaultChart(tx: Prisma.TransactionClient, companyId: string): Promise<number> {
  const result = await tx.account.createMany({
    data: DEFAULT_CHART.map((a) => ({ companyId, code: a.code, name: a.name, type: a.type })),
    skipDuplicates: true,
  });
  return result.count;
}
