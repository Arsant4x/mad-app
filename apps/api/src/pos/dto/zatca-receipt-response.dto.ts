/**
 * ⚖️ **حقولُ رمز الإيصال — سعوديّةٌ فتسكن وحدتَها** (`§3.8` · `ق-١٣٥٠` · `ق-١٤٣٨`).
 *
 * رمزُ `QR` على الإيصال هو رمزُ الهيئة (الملحق ١ من قرار التنفيذ: «**إلزاميٌّ توليداً وطباعةً** على الفاتورة المبسّطة»)،
 * **واسمُه على السلك** `zatcaQr`/`zatcaStamped` — فصنفُ الردّ الذي يصفه يحمل علامةً سعوديةً بالضرورة. فيُفصل هنا، داخل حدود الوحدة
 * (المسارُ يحمل علامتها)، **وإيصالُ الكاشير في النواة يرثه** — فلا يقع في النواة إلا سطرُ الاستيراد: دَينٌ واحدٌ معلَنٌ بحجّته.
 *
 * ⚠️ **وما يُزيل الدَّين** اسمٌ محايدٌ على السلك (رمزُ الإيصال لا اسمُ الجهة) — **تغييرُ عقدٍ** يكسر مستهلكي الواجهة الخارجيين ⟸ لحكم المالك.
 */
import { ApiProperty } from '@nestjs/swagger';
import { ZatcaStatus } from '@prisma/client';

/**
 * ⚖️ **الإجازةُ قبل المشاركة** (`ق-١٢٦١` أ): الفاتورةُ الضريبيةُ الكاملة تُجاز لدى الهيئة قبل أن تُسلَّم — فبوّابتُها سعوديّةٌ تسكن هنا.
 * `required: true` بحال المستند لدى الهيئة ورسالته، أو `required: false` وحدَها. **والحالُ من تعداد `Prisma` لا قائمةٌ منسوخة**
 * — فقيمةٌ تُضاف إلى التعداد لا تُسقط الحارسَ الحيّ بلا خطأ ترجمة (مراجعةُ الصنف).
 */
export class PosClearanceResponse {
  required!: boolean;
  // تعدادُ Prisma — المُلحَقُ يقرؤه Object؛ وحاضرٌ في فرع `required: true` وحدَه.
  @ApiProperty({ enum: ZatcaStatus, required: false })
  status?: ZatcaStatus;
  message?: string;
}

export class PosReceiptStampResponse {
  /** حمولةُ رمز الإيصال (TLV بـbase64) — `null` حين يغيب الاسمُ القانونيّ أو الرقمُ الضريبيّ فلا رمزَ يصحّ. */
  zatcaQr!: string | null;
  /** خُتم المستندُ (التوقيعُ والرمزُ التساعيّ) — `false` بلا ختمٍ بعد. */
  zatcaStamped!: boolean;
}
