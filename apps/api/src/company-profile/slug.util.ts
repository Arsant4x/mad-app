/**
 * **معرّفُ النطاق الفرعيّ — شكلُه وقواعدُه** (`ق-١٣٠٣` · ك/⑬A2).
 *
 * والشكلُ **مصدرُه واحد**: هذا الملفّ يصفه، وقيدُ `CHECK` في القاعدة يُنفِذه، وحارسٌ
 * يقارنهما — فلا يفترقان يوماً. ⚠️ **ولا يُكتفى بالتحقّق في الطلب**: مسارٌ لا يمرّ به
 * (بذرةٌ · سكربتٌ · ترحيل) يكتب ما يشاء، **والقيدُ لا يُتخطّى**.
 */

/** ثلاثةُ أحرفٍ فأكثر وأربعون فأقلّ · صغيرةٌ وأرقامٌ وشرطة · ولا تبدأ بشرطةٍ ولا تنتهي بها. */
export const SLUG_PATTERN = /^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$/;

/** نصُّ القيد في القاعدة — **يُقارَن بالنمط أعلاه في حارسٍ** فلا يفترق أحدُهما عن الآخر. */
export const SLUG_CHECK_SQL = "^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$";

export function isValidSlug(value: string): boolean {
  return SLUG_PATTERN.test(value);
}

/**
 * **التطبيعُ قبل الفحص لا بعده**: التاجرُ يكتب «Alfa » فيُقصد `alfa`.
 *
 * ⚠️ **ولا يُطبَّع إلا ما لا يغيّر المعنى**: الأحرفُ الكبيرة والفراغُ المحيط. **ولا
 * تُحذف الشرطاتُ ولا تُستبدَل الحروفُ العربية** — فمن كتب ما ليس معرّفاً يُردّ باسمه،
 * ولا يُخمَّن له معرّفٌ لم يكتبه.
 */
export function normalizeSlug(value: string): string {
  return value.trim().toLowerCase();
}
