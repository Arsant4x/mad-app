import { Prisma } from '@prisma/client';

type Rate = Prisma.Decimal | number | string;

/**
 * ⚖️ **سعرُ الذمّة لما لم يُخصَّص من سند العميل** (`ق-١٤٨٩` — المسار B6: سندُ الردّ لمرتجع).
 *
 * **سندُ القبض**: ما لم يُخصَّص منه خفّض `1200` **بسعر السند نفسِه** (دفعةٌ على الحساب — `baseSettledOf`)،
 * فسعرُ الصفّ هو سعرُ الذمّة ولا فرقَ بينهما.
 *
 * **وسندُ الردّ استثناءٌ مسمّى**: نقدُه يخرج **بسعر يوم الردّ** — وهو المخزَّن على الصفّ، لأن كلَّ مبلغٍ يحمل «سعرَ
 * الصرف وقتَ العملية» (`§6.7`) — **وذمّتُه تعود إلى `1200` بسعر إشعاره الدائن**، لأن الإشعار خفّض `1200` بذلك السعر
 * (والإشعارُ بسعر فاتورته حرفاً). والفرقُ بين السعرين فرقُ صرفٍ محقَّق على `5600`، لا يُطوى في النقد ولا في الذمّة.
 * **وعكسُ الردّ مرآتُه**: ذمّتُه بسعر إشعار الردّ الذي يعكسه، ونقدُه بسعر الردّ المنسوخ على صفّه.
 *
 * ⚠️ **مصدرٌ واحد لقارئَين** — مُرحِّلُ العكس (`PaymentsService.reverse`) ومطابقةُ الأعمار (`customerExposure`):
 * لو قرأ أحدُهما سعرَ الصفّ والآخرُ سعرَ الإشعار لصنعا في مطابقة `1200` **فرقاً غيرَ منسوب** بقدر فرق الصرف —
 * وهو ما كان سيصنعه تخزينُ سعر يوم الردّ على الصفّ وحده، بلا هذه القراءة.
 *
 * **ولا يُغيّر شيئاً فيما سبقه**: ردٌّ أُنشئ قبل `ق-١٤٨٩` خُزّن بسعر إشعاره، فالقراءتان تتطابقان عليه حرفاً.
 */
export function unallocatedReceivableRate(voucher: {
  exchangeRate: Rate;
  /** إشعارُ الردّ — لسند الردّ وحدَه (`kind = REFUND`). */
  refundsInvoice?: { exchangeRate: Rate } | null;
  /** الأصلُ الذي يعكسه السند — ولعكس الردّ إشعارُ ردّه. */
  reverses?: { refundsInvoice?: { exchangeRate: Rate } | null } | null;
}): number {
  const noteRate = voucher.refundsInvoice?.exchangeRate ?? voucher.reverses?.refundsInvoice?.exchangeRate;
  return Number(noteRate ?? voucher.exchangeRate);
}
