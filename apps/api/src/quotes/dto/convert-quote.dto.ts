import { IsBoolean, IsOptional } from 'class-validator';

/**
 * ⚖️ **تحويلُ عرض السعر يفتح ذمّةً كالفاتورة المباشرة — فيملك تصريحَها**
 * (`ق-٣٣٨`).
 *
 * ⚠️ **وبدونه تصير القناتان مختلفتين**: يُمنع التاجرُ في الفاتورة المباشرة
 * **ويمرّ من التحويل**، **فيصير التحويلُ بابَ التفافٍ على الحدّ** — وهو نقيضُ
 * «لا مسار فوترة موازٍ» التي بُني عليها التحويلُ أصلاً.
 *
 * **وحارسُ التكافؤ القائم** (`quotes.e2e-spec`) **يقيس هذا بعينه**.
 */
export class ConvertQuoteDto {
  @IsOptional()
  @IsBoolean()
  creditOverride?: boolean;
}
