import { localDateOf } from '../common/wall-clock.util';

/**
 * ⚖️ **انقضاءُ عرض السعر يُقاس بيومٍ معلَن لا بتوقيت العملية** (`ق-١١٨٣`).
 *
 * ## العطل الذي كان
 * `isExpired` كان يضبط نهايةَ يوم الصلاحية بـ`setHours(23, 59, 59, 999)` **بمنطقة العملية**، بينما
 * `validUntil` عمودُ `@db.Date` يُحلَّل **UTC حصراً**. فعلى خادمٍ بتوقيت الرياض ينقضي العرضُ الصالحُ
 * حتى `2026-09-19` عند `21:00 UTC` من يومه — قبل نهاية يومه المعلَن بثلاث ساعات — وعلى خادمٍ غربَ
 * غرينتش بعدها. **والخدمةُ هي التي تقرّر متى ينتهي عرضُ التاجر — فخطؤها يقع على تاجرٍ لا على اختبار**
 * (بنصّ المالك)، والعضوُ الثالث من عائلة «يومُ الرياض ويومُ `UTC`» بعد `rejected-replacement ④`.
 *
 * ## القاعدة — كقفل الفترات
 * اليومُ المخزَّن يُقرأ كما خُزِّن (`YYYY-MM-DD` من `toISOString`)، ويومُ الآن يُشتقّ بإزاحةٍ **معلَنة**
 * (`localDateOf` — الدالّةُ التي تحسب يومَ الكاشير من إزاحة جهازه، `ق-١٨٥`) لا بمنطقة العملية؛ والعرضُ
 * منقضٍ حين يتجاوز يومُ الآن يومَ الصلاحية — **فآخرُ يومٍ مشمول**، ولا `setHours` ولا `getDate` هنا.
 *
 * ⚠️ **حدٌّ معلَن**: بلا إزاحةٍ مُعلَنة يُقرأ يومُ الآن بـ`UTC` (`offsetMin = 0`) — فتاجرُ الرياض يرى عرضَه
 * حيّاً ثلاثَ ساعاتٍ بعد منتصف ليله. والإزاحةُ من الجهاز (كما `ringOffsetMin` في الكاشير) بابٌ لا يُفتح هنا.
 */
export function isQuoteExpired(quote: { validUntil: Date; status: string }, now: Date = new Date(), offsetMin = 0): boolean {
  if (quote.status === 'CONVERTED') return false;
  const validUntil = quote.validUntil.toISOString().slice(0, 10);
  return localDateOf(now, offsetMin) > validUntil;
}
