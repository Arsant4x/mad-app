-- ⭐ تاريخُ الافتتاح الذي يعلنه التاجر (ق-٢٩٦)
--
-- ## لماذا فارغٌ ولا يُملأ
--
-- كان تاريخُ القيد الافتتاحيّ **يُشتقّ**: بدايةُ السنة المالية أو **اليوم**.
-- فصار في الواقع **يومَ تشغيل الترحيل الرجعيّ** — مِرساةٌ مصطنعة (ق-٢٩١).
--
-- والحكم (ق-٢٩٦/ب): العمودُ يصير صادقاً من أول يوم. **وتنفيذُه هنا بلا كتابة
-- صفٍّ واحد**: `NULL` تعني **«اقرأه من الأستاذ»** — فالعرضُ يشتقّه من تاريخ
-- القيد الافتتاحيّ نفسه، **والقيمةُ لا تُكتب إلا حين يعلنها التاجر**.
--
-- ⚠️ **والمقيس هو ما منع المِلء** (ق-٢٩٦/⑤): من ١٣١ حساباً ذا قيدٍ افتتاحيّ
-- **٣٥ (٢٧٪) له حركةٌ بعده** فيُقفَل تاريخُه؛ **ومن ١٢ حسابَ بنكٍ يحمل تاريخاً
-- أعلنه التاجر، ١٢ يخالف تاريخَ قيده** (يناير مقابل سبتمبر). فمِلءُ العمود
-- بالمشتقّ كان **يمحو الفرق بين ما أعلنه التاجر وما حسبه سكربت** — وهو الفرقُ
-- الذي طُلب قياسُه.
--
-- ⚠️ **ولا `DML` هنا إطلاقاً** — فلا حاجةَ لرفع `FORCE` عن `accounts`
-- (ق-٢٦٢): إضافةُ عمودٍ فارغ `DDL` محضة، ولا صفَّ يُقرأ ولا يُكتب.

ALTER TABLE "accounts" ADD COLUMN "openingDate" DATE;
