--
-- كان يُحسب في الاستجابة **ويُرمى**: لا عمودَ له إطلاقاً. ورقمٌ يُعاد حسابه
-- بعد شهور **يتبع الشيفرةَ الحالية لا الحالةَ وقت الإقفال** — فتغييرٌ في
-- معادلة الحساب يُعيد كتابة تاريخٍ بلا قيد (حكم المالك).
--
-- `NULL` = لم تُقفل بعد **أو** أُقفلت قبل هذه الموجة: **تُعلَن ولا تُرحَّل
-- رجعياً** (كالـ٤٦٨). والمقيس على المنشورة: **مناوبتان مقفلتان فقط**.
--
-- ⚠️ ولا `DML` هنا: إضافةُ عمودٍ فارغ `DDL` محضة، فلا حاجةَ لرفع `FORCE`
-- عن `pos_shifts` (ق-٢٦٢) — لا صفَّ يُقرأ ولا يُكتب.

