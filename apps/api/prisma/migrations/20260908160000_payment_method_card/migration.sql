-- ⭐ «شبكة» طريقةَ دفعٍ ثالثة (ق-٣٢٠)
--
-- كان `PaymentMethod` نقداً أو بنكاً وحدهما، **فسندُ بيعٍ بالشبكة لا تمثيلَ
-- له**. والبديلُ المرفوض: تسجيلُه `BANK` بحساب `1251` — «**بنكٌ بلا بنك صفٌّ
-- يكذب**، ورقمٌ يُقرأ خطأً في كل تقريرٍ يجمع بالطريقة» (حكم المالك).
--
-- والاسمُ في الواجهة **«شبكة»** لا «بطاقة»: هي ما يقوله التاجرُ السعوديّ.
-- وحسابُها `1251` وحده — لا `1000` ولا حسابُ بنك.
--
-- ⚠️ ولا `DML`: إضافةُ قيمةٍ إلى نوعٍ مُعدَّد لا تقرأ صفّاً ولا تكتبه،
-- فلا حاجةَ لرفع `FORCE` عن شيء (ق-٢٦٢).

ALTER TYPE "PaymentMethod" ADD VALUE 'CARD';
