-- الملحقُ فقط يمنع إعادةَ كتابة التاريخ — **ولا يمنع المحو** (ق-١٣٠٣ · ك/⑰A1).
--
-- ── العلّة، مقيسةً لا مُرجَّحة ──────────────────────────────────────────────
--
-- المشغِّلُ في الهجرة السابقة كان يرفض **كلَّ** حذفٍ — **والحذفُ المتسلسل يمرّ به**.
-- فقِيس على القاعدة النظيفة: إدراجُ عميلٍ وموافقةٍ ثم `DELETE FROM customers` ⇒
--
--     ERROR: سجل الموافقة التسويقية ملحقٌ فقط — لا يُحذف منه صفّ
--
-- أي أن **عميلاً وافق مرّةً لا يُمحى أبداً، ومنشأتَه معه** — وهو نقضٌ لحقّ المحو
-- (النظام م٤: لصاحب البيانات طلبُ إتلافها) ولمسار حذف الحساب في المنتج. وأمسكته
-- حزمةُ الـ`e2e` عند تنظيفها: «منشأةُ الاختبار لم تُزَل».
--
-- ── والقاعدة الصحيحة: أعِد صياغةَ ما يُمنع ────────────────────────────────
--
-- **المنعُ على إعادة كتابة التاريخ**، لا على زوال صاحبه. فالإثباتُ يُحفظ **ما دام
-- صاحبُه قائماً** (اللائحة م٢٨/٣) — **ومتى مُحي هو، ذهب إثباتُه معه**: لا إرسالَ
-- بعده فلا معنى لإثباتٍ عنه.
--
-- ── والتمييزُ مقيسٌ أيضاً، لا مفترَض ───────────────────────────────────────
--
-- `ON DELETE CASCADE` يُنفَّذ بعد حذف صفّ الأب، **فلا يراه المشغِّلُ موجوداً**. قِيس
-- بتبديل الدالّة داخل معاملةٍ تُرجَع على القاعدة النظيفة:
--
--     حذفُ العميل (تسلسل)                    ⇒ مرّ · وبقي 0 صفّاً
--     حذفُ صفّ الموافقة والعميلُ قائم        ⇒ رُفض
--     تعديلُ الصفّ                            ⇒ رُفض
--
-- **وشرطُ المنشأة معه**: حذفُ المنشأة يُسلسِل على `customers` و`marketing_consents`
-- **بترتيبٍ غير مضمون** — فلو سبق ثانيهما لبقي العميلُ موجوداً ورُفض الحذف. وصفُّ
-- المنشأة يُحذف قبل تسلسلاتها، فيكفي غيابُ أحدهما.
--
-- ⚠️ **وحدُّه معلَن**: من محا العميلَ يستطيع محوَ موافقاته — **وهو المقصود** لا ثغرة:
-- محوُ العميل نفسُه فعلٌ مُدقَّق في مسار حذف الحساب، وليس طريقاً خفيّاً.

CREATE OR REPLACE FUNCTION marketing_consents_append_only() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        -- محوُ صاحب البيانات (أو منشأته) يجرّ إثباتَه معه — وما عداه إعادةُ كتابةٍ للتاريخ.
        IF EXISTS (SELECT 1 FROM "customers" WHERE "id" = OLD."customerId")
           AND EXISTS (SELECT 1 FROM "companies" WHERE "id" = OLD."companyId") THEN
            RAISE EXCEPTION 'سجل الموافقة التسويقية ملحقٌ فقط — لا يُحذف منه صفّ (اللائحة م٢٨/٣: يُحتفظ بإثبات الموافقة). ويزول مع محو العميل نفسِه.';
        END IF;
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'سجل الموافقة التسويقية لا يُعدَّل — الرجوعُ عن الموافقة صفٌّ جديد.';
END;
$$ LANGUAGE plpgsql;
