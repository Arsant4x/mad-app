-- ⭐ حدُّ الائتمان يُفعَّل: إعدادُ المنع الصلب، وتجاوزٌ يُخزَّن على الفاتورة
-- (ق-٣٣٦ · ق-٣٣٩ · ق-٣٤٠)
--
-- ── لماذا ────────────────────────────────────────────────────────────────
--
-- `Customer.creditLimit` قائمٌ منذ البداية: **يُخزَّن ويُحرَّر ويُعرض في جدول
-- العملاء — ولا قارئَ له في أيّ قرار** (ق-٣٣٢①). وحكمُ المالك: «**حقلٌ يراه
-- التاجر ويظنّه يحميه ولا يفعل شيئاً أخطر من غيابه**» (ق-٣٣٦).
--
-- ── العمودان وما يمثّلانه ────────────────────────────────────────────────
--
-- ① `Company.creditLimitHardBlock` — **المنعُ الصلب إعدادٌ يختاره التاجر**
--    (ق-٣٤٠)، **مطفأً افتراضياً** على سابقة `writeOffRequiresTwoPersons`
--    نصّاً: «**منعٌ واحدٌ للجميع يفرض على متجرٍ صاحبُه وحده ما لا يحتمله**».
--
-- ② أعمدةُ التجاوز الأربعة على `invoices` — **من تجاوز · ومتى · وكم كان
--    التعرّض · وكم كان الحدّ** (ق-٣٣٩). ⚠️ **والتعرّضُ والحدُّ يُخزَّنان
--    لحظتَهما ولا يُشتقّان بعدُ**: التعرّضُ يتغيّر بكل سداد، والحدُّ يُحرَّر
--    في شاشة العملاء — **فقراءتُهما لاحقاً من الحيّ تُنتج شهادةً على غير ما
--    وقع**. وهو **مستندُ واقعةٍ لا حالةٌ موازية**، فلا يخالف القاعدة ١١.
--
-- ── ولا `DML` هنا ────────────────────────────────────────────────────────
--
-- ⚠️ **أعمدةٌ تُضاف بقيمةٍ ثابتة لا تقرأ صفّاً ولا تكتب صفّاً** — والقيمُ
-- الافتراضية يضعها المحرّك بلا `UPDATE`. **فلا رفعَ لـ`FORCE ROW LEVEL
-- SECURITY` ولا حاجةَ إليه** (ق-٢٦٢): الرفعُ يلزم حين يمسّ الترحيلُ صفوفاً
-- تحت سياسةٍ تمنع مالكَ الجدول، وليس هذا منه.
--
-- ⚠️ **ولا مفتاحَ أجنبيّ على `creditOverrideById`** — عن قصدٍ لا سهو:
-- المتجاوِزُ قد يكون **مالكاً (`LoginIdentity`) أو موظفاً (`CompanyUser`)**،
-- وهما جدولان. **وهو نمطُ `AuditLog.actorId` نفسُه** في هذه القاعدة —
-- فيُتَّبع ولا يُخترع، والاسمُ يُقرأ عند العرض من الجدول الذي يخصّه.

ALTER TABLE "companies" ADD COLUMN "creditLimitHardBlock" BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE "invoices"
  ADD COLUMN "creditOverrideById"     TEXT,
  ADD COLUMN "creditOverrideAt"       TIMESTAMP(3),
  ADD COLUMN "creditOverrideExposure" DECIMAL(18,2),
  ADD COLUMN "creditOverrideLimit"    DECIMAL(18,2);
