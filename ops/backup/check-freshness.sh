#!/bin/sh
# ═══ الشرطُ الخامس: «كيف يُعرف أن نسخةَ الأمس لم تقع؟» (ق-٥٧٧) ═══
#
# ⭐ **يُقرأ من المستودع نفسِه لا من الخادم** — وهذا هو بيتُ القصيد:
#    مقياسٌ يسأل الخادمَ «هل نسختَ أمس؟» **يصمت حين يموت الخادم**، وهو العطلُ
#    الذي بُنيت له النسخةُ أصلاً. فالسؤالُ يُوجَّه إلى ما يبقى: المستودع.
#
# ⚠️ **ويُشغَّل من خارج المضيف**: جهازُ صاحب المشروع، أو مهمّةٌ مجدولة عند أيّ
#    طرفٍ يملك عنوانَ المستودع وكلمتَه — **ولا يلزمه أن يكون الخادمُ حيّاً**.
#
# ⚠️ **ومُصادَقٌ بحالتين** (`ق-٣٧٠`): يُجرَّب على مستودعٍ حديثٍ فيمضي، وعلى أجلٍ
#    مستحيلٍ (`MAX_AGE_HOURS=0`) فيسقط — **فمقياسٌ لم يُر ساقطاً لا يُقرأ حكمُه**.
#
# الخروج: 0 = نسخةٌ حديثة · 1 = متقادمةٌ أو معدومة · 2 = تعذّر بلوغُ المستودع.
set -eu

: "${RESTIC_REPOSITORY:?RESTIC_REPOSITORY غير مضبوط}"
: "${RESTIC_PASSWORD:?RESTIC_PASSWORD غير مضبوط}"
MAX_AGE_HOURS="${MAX_AGE_HOURS:-26}"

latest=$(restic snapshots --latest 1 --json 2>/dev/null || true)
if [ -z "$latest" ] || [ "$latest" = "[]" ]; then
  echo "⛔ لا لقطةَ واحدة في المستودع — النسخةُ لم تقع قطّ، أو المستودعُ ليس هذا." >&2
  exit 1
fi

when=$(echo "$latest" | sed -n 's/.*"time":"\([^"]*\)".*/\1/p' | head -1)
short=$(echo "$latest" | sed -n 's/.*"short_id":"\([^"]*\)".*/\1/p' | head -1)
if [ -z "$when" ]; then
  echo "⛔ تعذّرت قراءةُ زمن آخر لقطة — لا يُحكم بالصمت." >&2
  exit 2
fi

# `date -d` متاحٌ في `coreutils` (صورةُ `restic` عليه) — والفشلُ يُعلَن ولا يُفترض نجاحاً.
ts=$(date -u -d "$when" +%s 2>/dev/null || true)
[ -n "$ts" ] || { echo "⛔ تعذّر تحويلُ زمن اللقطة ($when)." >&2; exit 2; }
now=$(date -u +%s)
age_h=$(( (now - ts) / 3600 ))

if [ "$age_h" -gt "$MAX_AGE_HOURS" ]; then
  echo "🔴 آخرُ نسخةٍ خارج المضيف عمرُها $age_h ساعة (الحدّ $MAX_AGE_HOURS) — لقطة ${short:-?} في $when. نسخةُ الأمس لم تقع." >&2
  exit 1
fi
echo "🟢 آخرُ نسخةٍ خارج المضيف عمرُها $age_h ساعة — لقطة ${short:-?} في $when."
