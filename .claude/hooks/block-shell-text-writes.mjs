#!/usr/bin/env node
/**
 * يمنع كتابة النصّ عبر الصدفة — **قاعدة تشغيلية لا تذكير**.
 *
 * ## أربع حوادث لا صدفة
 *
 * `node -e` و`python -c` وأمثالهما تمرّ بمُفسِّر الصدفة أولاً. والاقتباس
 * العكسي فيها **يُنفَّذ كأمر**، فيُستبدل بمخرَجه — وغالباً بالفراغ. والنتيجة
 * أن الشيفرة تُكتب سليمة **والنصّ العربي يُفرَّغ من كلماته** بلا خطأ ولا
 * تحذير: الأمر ينجح، والملف يُحفظ، والكلمة تختفي.
 *
 * وقع هذا **أربع مرات** في هذا المشروع:
 *   ① أربع كتل في CLAUDE.md فُرِّغت بينما طبع الأمر «نجاح»
 *   ② تعليقان في `create-activity.dto.ts` و`update-activity.dto.ts`
 *      فقدا `SECTORS` و`sectorSuggested`
 *
 * ولم يُمسك أيٌّ منها إلا **بقراءة الملف بعد الكتابة**. أي أن الحارس كان
 * عادةً بشرية تُنسى — وأربع مرات تجعلها نمطاً لا صدفة.
 *
 * ## ما يمنعه بالضبط
 *
 * تنفيذ نصٍّ برمجي داخل الصدفة (`-e` · `-c` · `-p`) **حين يكتب ملفاً**.
 * والقراءة والفحص لا تُمنعان: `node -e "console.log(...)"` يمرّ.
 *
 * ## والبديل ليس أصعب
 *
 * أدوات `Write`/`Edit` تكتب البايتات كما هي بلا مُفسِّر بينها. ولنقلٍ
 * كتليّ من الصدفة: `cat > file <<'EOF'` — والاقتباس المفرد حول `EOF`
 * يمنع كل تفسير.
 */
import { readFileSync } from 'node:fs';
// ⚠️ استيرادٌ ثابت لا `require`: هذا الملف **وحدة ESM** (`.mjs` مع `import`)،
// و`require` فيها غير معرَّفة. و`node --check` يمرّ عليها لأنها صياغةٌ سليمة —
// **والفحص النحوي ليس تشغيلاً**. كُشف بتشغيل الخطّاف فعلاً لا بقراءته.
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';

let payload;
try {
  payload = JSON.parse(readFileSync(0, 'utf8'));
} catch {
  process.exit(0); // مُدخَل غير مفهوم ⇒ لا يُعطَّل العمل
}

if (payload?.tool_name !== 'Bash') process.exit(0);
const cmd = String(payload?.tool_input?.command ?? '');

/** مُفسِّرٌ يُنفِّذ نصّاً من سطر الأوامر. */
const INLINE_SCRIPT = /\b(node|python3?|ruby|perl|deno|bun)\s+(-[A-Za-z]*[ecp])\b/;
/** ...ويكتب ملفاً. */
const WRITES_FILE = /writeFileSync|appendFileSync|createWriteStream|fs\.write|open\s*\([^)]*['"][wa]|\.write_text|>>?\s*['"]?[\w./\\-]+\.(ts|tsx|js|mjs|json|md|sql|ya?ml|txt)/;

/**
 * ## الحادثة الخامسة — الاقتباس العكسي في **وسيطِ أمر** لا في ملف (2026-08-15)
 *
 * كُتب جسم طلبٍ داخل `gh pr create --body "…"` — سلسلةٌ مقتبَسة اقتباساً
 * **مزدوجاً**. والاقتباس العكسي حول أسماء الحقول (`` `startDate` `` وأمثالها)
 * **نُفِّذ كأمر** واستُبدل بمخرَجه الفارغ، **فأُفرغت ثلاث كلمات**.
 *
 * وهي العلّة نفسها التي بُني لها هذا الخطّاف — **في موضعٍ لم يكن يحرسه**:
 * كان يفحص `node -e` الكاتبَ للملفات، ولا يفحص وسيطاً نصّياً يمرّ بالصدفة.
 * **فبوّابةٌ تحرس باباً وتترك نافذة.**
 *
 * ### القاعدة
 *
 * الاقتباس العكسي آمنٌ داخل **الاقتباس المفرد** أو **heredoc بحرف إنهاء
 * مقتبَس** (`<<'EOF'`) — لأن الصدفة لا تفسّر ما بداخلهما. وخطرٌ في كل ما عداه.
 *
 * فيُجرَّد الآمن أولاً، وما بقي من اقتباسٍ عكسي **يُرفض**. والبديل موجود
 * ومستعمَل في هذا المشروع: `$( )` للتنفيذ، و`--body-file` مع heredoc مقتبَس
 * للنصوص.
 */
const stripSafeSpans = (c) =>
  c
    // heredoc بحرف إنهاء مقتبَس: <<'EOF' … EOF  (لا تفسير بداخله إطلاقاً)
    .replace(/<<-?\s*'([A-Za-z_][A-Za-z0-9_]*)'[\s\S]*?^\s*\1\s*$/gm, '')
    // سلاسل مقتبَسة اقتباساً مفرداً
    .replace(/'[^']*'/g, '');

if (/`/.test(stripSafeSpans(cmd))) {
  console.error(
    [
      '⛔ ممنوع: اقتباسٌ عكسي خارج الاقتباس المفرد أو الـheredoc المقتبَس.',
      '',
      'الصدفة تُنفِّذه كأمرٍ وتستبدله بمخرَجه — وغالباً بالفراغ. فتُكتب الكلمة',
      'وتختفي بلا خطأ ولا تحذير.',
      '',
      'وقع خمس مرات في هذا المشروع، آخرها 2026-08-15 في `gh pr create --body "…"`:',
      'أُفرغت ثلاث كلمات من جسم طلبٍ منشور، وأُمسكت بقراءته بعد النشر لا قبله.',
      '',
      'البديل:',
      "  · للنصوص:   --body-file /tmp/x.md   مع   cat > /tmp/x.md <<'EOF'",
      '  · للتنفيذ:  $( )  بدل  `` ',
      '  · وللملفات: أدوات Write / Edit',
    ].join('\n'),
  );
  process.exit(2);
}

if (INLINE_SCRIPT.test(cmd) && WRITES_FILE.test(cmd)) {
  console.error(
    [
      '⛔ ممنوع: كتابة ملفٍّ عبر نصٍّ مُضمَّن في الصدفة.',
      '',
      'الاقتباس العكسي داخل `node -e` يُنفَّذ كأمرٍ ويُستبدل بمخرَجه — غالباً بالفراغ.',
      'فتُكتب الشيفرة سليمة ويُفرَّغ النصّ من كلماته، بلا خطأ ولا تحذير.',
      'وقع أربع مرات في هذا المشروع، ولم يُمسك أيٌّ منها إلا بقراءة الملف بعد الكتابة.',
      '',
      'البديل: أدوات Write / Edit — تكتب البايتات كما هي بلا مُفسِّر بينها.',
      "ولنقلٍ كتليّ: cat > file <<'EOF'  (الاقتباس المفرد يمنع كل تفسير).",
    ].join('\n'),
  );
  process.exit(2); // 2 = رفضٌ يُعاد إلى النموذج مع السبب
}

/**
 * ## الحادثة الخامسة — مُفسِّرٌ ينجح صامتاً ولا ينفّذ (2026-08-15)
 *
 * حُقن كسرٌ للإثبات العكسي عبر `python - <<'PY'`. **مرّ الحارس أخضر — ولم يكن
 * ذلك نجاحاً**: الكسر لم يقع أصلاً. و`python` هنا **كعب متجر ويندوز** في
 * `WindowsApps`: موجودٌ في `PATH` فيُرضي `command -v`، **بلا مخرجات، ويخرج
 * بالرمز 0، ولا يفعل شيئاً**. و`py` غير موجود، و`python3` كعبٌ مثله.
 *
 * وهو أخطر من المنع: **إثباتٌ عكسي لم يقع يبدو مطابقاً تماماً لإثباتٍ نجح.**
 * فكل حارسٍ يُثبَت بعده يحمل شهادةً باطلة.
 *
 * والفحص أدناه **يقرأ البيئة ولا يفترضها**: يُرفض النداء فقط إن كان المسار
 * المُحلَّل كعباً. فإن ثُبِّت Python حقيقي لاحقاً، مرّ بلا تعديل هنا.
 */
const PYTHON_CALL = /(^|[|&;(\s])python3?(\s|$)/;
if (PYTHON_CALL.test(cmd)) {
  const { execFileSync } = await import('node:child_process');
  let resolved = '';
  try {
    resolved = (execFileSync('where', ['python'], { encoding: 'utf8' }).split(/\r?\n/)[0] ?? '').trim();
  } catch {
    resolved = ''; // غير موجود إطلاقاً ⇒ الصدفة ستقول ذلك بصوتٍ عالٍ، فلا نتدخّل
  }
  if (/WindowsApps/i.test(resolved)) {
    console.error(
      [
        '⛔ ممنوع: `python` في هذه البيئة **كعبُ متجر ويندوز** — لا مُفسِّر.',
        '',
        `المسار المُحلَّل: ${resolved}`,
        'سلوكه: بلا مخرجات · يخرج بالرمز 0 · ولا ينفّذ شيئاً.',
        '',
        'فالأمر «ينجح» ولا يحدث. ولو كان إثباتاً عكسياً، لبدا الحارسُ سليماً وهو لم يُختبر.',
        'وقع في 2026-08-15 على حقن كسرٍ في companies.service.ts.',
        '',
        'البديل: `node` (مُفسِّر حقيقي هنا) — أو أدوات Write/Edit للكتابة.',
      ].join('\n'),
    );
    process.exit(2);
  }
}

/**
 * ## القاعدة التاسعة — بوّابةً لا تذكيراً (قرار المالك 2026-08-15)
 *
 * كانت: «`rm` و`git clean` وأي حذف يُنفَّذ بعد `pwd` معلن في نفس الأمر». وهي
 * **عادة بشرية تُنسى في أول ضغط** — وقد ثبت ذلك في اليوم نفسه: بُني عنوان قاعدة
 * الفحص بـ`sed`، **وطُبع في المخرَج**، ثم مضى التنفيذ. ولم يطابق `sed` لوجود
 * `?schema=public`، فطُبِّقت الترحيلات على قاعدة التطوير. **الهدف كان مكتوباً
 * ولم يُقرأ.**
 *
 * ⬅️ فالإعلان **مخرَجٌ يُقرأ إن شئت**، والبوّابة **شرطٌ يمنع المضيّ**.
 *
 * ### ما يُشترط
 *
 * كل أمرٍ **مُتلِف أو مُهاجِر** يجب أن يحمل **في النصّ نفسه** ما يثبّت هدفه:
 * إمّا **مسار مطلق** في وسيطه، وإمّا **بوّابة `case`/`if` تخرج بخطأ** عند عدم
 * المطابقة، وإمّا `pwd` معلن **مع** مسارٍ مطلق.
 *
 * ولا يُقبل `echo "$X"` وحده: طباعةُ المتغيّر **ليست فحصاً له**.
 */
// ⚠️ الحدّ الأيسر `[^\w-]` لا `\s`: أولُ صيغةٍ كتبتُها اشترطت مسافةً أو فاصلاً
// قبل الكلمة، فمرّت `psql -c "DROP DATABASE $DB"` — إذ يسبق `DROP` علامةُ
// اقتباس. كشفه الإثبات العكسي: حالةٌ من ستّ. والسطر الذي يحرس الحذف كان يمرّ
// على أوضح صيغة حذفٍ في المشروع.
const SHELL_DESTRUCTIVE = /(^|[^\w-])(rm\s+-[a-zA-Z]*[rf]|git\s+clean|prisma\s+migrate\s+(deploy|reset)|migrate\s+reset)/i;

// وكلماتُ SQL **لا تُعدّ مُتلِفةً بذاتها** — `grep "DROP DATABASE" docs/` بحثٌ لا
// تنفيذ، وقد رفضتْه الصيغةُ الأولى. فتُشترط بسياقٍ مُنفِّذ في الأمر نفسه.
// (كشفه الإثبات العكسي أيضاً: إيجابيّةٌ كاذبة تدفع إلى تعطيل الحارس، وحارسٌ
// يُعطَّل لا يحرس.)
const SQL_DESTRUCTIVE = /(^|[^\w-])(DROP\s+DATABASE|DROP\s+TABLE|TRUNCATE\s+TABLE)/i;
const SQL_EXECUTOR = /\b(psql|mysql|mongo|sqlite3|\$executeRaw|\$queryRaw|executeRawUnsafe)\b/;

const DESTRUCTIVE = {
  test: (c) => SHELL_DESTRUCTIVE.test(c) || (SQL_DESTRUCTIVE.test(c) && SQL_EXECUTOR.test(c)),
};
/** بوّابةٌ تمنع المضيّ فعلاً — لا مجرّد طباعة. */
const HAS_GATE = /case\s+"?\$|if\s+\[\[?[^\]]*\]\]?\s*(;|\n)\s*(then|&&)|\|\|\s*(exit|return)\s+1|grep\s+-q[a-zA-Z]*\s/;
/** مسارٌ مطلق مكتوب صراحةً في الأمر — ويكفي وحده لتثبيت الهدف. */
const ABSOLUTE_TARGET = /(^|\s)(\/[a-zA-Z]|[A-Za-z]:[\\/]|D:\/|\/d\/|\/opt\/|\/tmp\/)/;

if (DESTRUCTIVE.test(cmd) && !HAS_GATE.test(cmd) && !ABSOLUTE_TARGET.test(cmd)) {
  console.error(
    [
      '⛔ ممنوع: أمرٌ مُتلِف أو مُهاجِر بلا هدفٍ مثبَّت **في نصّ الأمر نفسه**.',
      '',
      'القاعدة التاسعة صارت بوّابة (قرار المالك 2026-08-15): الإعلان مخرَجٌ يُقرأ',
      'إن شئت، والبوّابة شرطٌ يمنع المضيّ. و«أعلنه ثم تحقّق» عادةٌ بشرية تُنسى.',
      '',
      'الحادثة: بُني عنوان قاعدة بـsed وطُبع في المخرَج ثم مضى التنفيذ — ولم يطابق',
      'sed لوجود ?schema=public، فطُبِّقت الترحيلات على قاعدة التطوير. الهدف كان',
      'مكتوباً ولم يُقرأ.',
      '',
      'المقبول أحد ثلاثة:',
      '  ١. مسار مطلق في الأمر:      rm -f /tmp/x  ·  rm -rf D:/worktrees/y',
      '  ٢. بوّابة تخرج بخطأ:         case "$DB" in *wave0*) : ;; *) exit 1 ;; esac',
      '  ٣. أو:                      [[ "$T" == /opt/mad-app/* ]] || exit 1',
      '',
      '⚠️ و`echo "$TARGET"` وحده لا يكفي — طباعة المتغيّر ليست فحصاً له.',
    ].join('\n'),
  );
  process.exit(2);
}

/**
 * ═══ بوّابة الدمج: حالة الطلب تُقرأ **قبل** الدمج لا معه ═══
 *
 * ## الحادثة (2026-08-16)
 *
 * طُلب دمج `#61`، فقُرئت حالته **في نفس الأمر الذي دمج**:
 *
 *     gh pr view 61 --json … && gh pr merge 61 --merge
 *
 * فطُبعت `UNSTABLE` **ومضى الدمج قبل أن تُقرأ**. و`db-integration` كانت ساقطة،
 * فصارت `main` حمراء. والفحص كان بين اليدين **ولم يمنع شيئاً** لأنه مخرَجٌ
 * يُقرأ لا شرطٌ يُختبَر — وهي عائلة §8.10: **الإعلان ليس قراءة**.
 *
 * ⚠️ **وأمرُ المالك بالدمج لا يُسقط قراءة ما بين يديك** (قراره 2026-08-16):
 * فهو يأمر بالدمج على أساس أن الحالة سليمة، لا على أساس أن تُتجاهَل.
 *
 * ## ولماذا يستعلم هذا الحارس بنفسه
 *
 * حارسٌ يشترط «اقرأ الحالة أولاً» يعود عادةً بشرية تُنسى — وهي التي فشلت هنا.
 * فيسأل **هو** ويمنع المضيّ (§8.11: كل قاعدة تُنفَّذ بوّابةً أو لا تُعتمد).
 *
 * ## الإذن الصريح
 *
 * `MERGE_UNSTABLE_OK=1` في نصّ الأمر — ولا تُكتب إلا بإذن المالك **في نفس
 * رسالته**. فهي أثرٌ مقروء في السجل، لا مفتاحٌ صامت.
 */
const MERGE_CMD = /(^|[^\w-])gh\s+pr\s+merge(\s|$)/;

if (MERGE_CMD.test(cmd)) {
  if (/MERGE_UNSTABLE_OK=1/.test(cmd)) process.exit(0); // إذنٌ صريح، وأثرُه في الأمر

  const prNumber = cmd.match(/gh\s+pr\s+merge\s+(\d+)/)?.[1] ?? '';
  const args =['pr', 'view', ...(prNumber ? [prNumber] : []), '--json', 'number,state,mergeStateStatus,headRefName'];
  /**
   * ⚠️ **يسأل من جذرٍ يملكه لا من جذر الجلسة** (2026-09-04).
   *
   * أول ما رُبط الخطّاف على مستوى المستخدم **منع كل دمج**: `gh` كان يُستدعى
   * في مجلَّد الجلسة (`C:/…/Desktop/mad-app`) — **وليس مستودعاً**، فردّ
   * `not a git repository`. والبوّابة **رفضت بحقّ** (الفشل مُغلِق)، لكنها
   * كانت ترفض الصالح والفاسد معاً.
   *
   * والعلّة نفسها التي عالجها `ق-١٤٩`، **ظاهرةً هذه المرة داخل الخطّاف**:
   * اعتمادٌ ضمنيّ على أن جذر الجلسة هو المستودع. والخطّاف يسكن المستودع الذي
   * يحرسه، **فيسأل عنه من موضعه** — فلا يعود جذرُ الجلسة شرطاً هنا أيضاً.
   */
  const repoRoot = resolve(import.meta.dirname, '..', '..');
  const probe = spawnSync('gh', args, { encoding: 'utf8', shell: process.platform === 'win32', cwd: repoRoot });

  // ⚠️ **يُفحص نجاح الاستعلام قبل قراءة نتيجته** (§8.8): استعلامٌ فاشل يُقرأ
  // حالةً فارغة — أي أن الحارس يمرّ على كل شيء وهو يظنّ نفسه يعمل.
  let status = null;
  let number = prNumber || '?';
  let headRef = null;
  if (probe.status === 0) {
    try {
      const parsed = JSON.parse(probe.stdout);
      status = parsed.mergeStateStatus ?? null;
      number = parsed.number ?? number;
      headRef = parsed.headRefName ?? null;
    } catch {
      status = null;
    }
  }

  /**
   * ⏳ **`UNKNOWN` تُنتظَر، لا تُقبل ولا تُرفض فوراً** (`ق-٢٦٠` — قرار المالك 2026-09-07).
   *
   * بعد كل دمج يُبطل GitHub حسابَ القابلية ويعيده `UNKNOWN` دقائقَ حتى يفرغ من
   * حسابه. **والقبولُ الفوري عطل**: دمجٌ قبل أن يُعرف شيء — وهو ما بُنيت هذه
   * البوّابة لمنعه (حادثة #61). **والرفضُ الفوري خطأٌ آخر**: يوقف دمجاً صالحاً
   * ويجعل كلَّ طلبٍ بعد طلبٍ يفشل مرةً بلا سبب.
   *
   * فالبوّابة **تنتظر بثلاث محاولات** بفواصل متصاعدة، ثم ترفض **مسمّيةً الحالة
   * والمهلة** — لأن رسالةً تقول «مجهولة» بلا رقمٍ تُقرأ عطلاً في الأداة.
   *
   * ⚠️ وكان هذا **عادةً بشرية**: صادفتُها قبل دمج #169 فانتظرتُ بيدي حتى صارت
   *    `CLEAN`. **والانتظارُ عادةٌ تُنسى، وهذه بوّابة** (§8.11).
   */
  const UNKNOWN_TRIES = 3;
  const UNKNOWN_WAIT_MS = [2000, 4000, 6000];
  const sleepSync = (ms) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
  let waitedMs = 0;
  for (let i = 0; status === 'UNKNOWN' && i < UNKNOWN_TRIES; i += 1) {
    sleepSync(UNKNOWN_WAIT_MS[i]);
    waitedMs += UNKNOWN_WAIT_MS[i];
    const again = spawnSync('gh', args, { encoding: 'utf8', shell: process.platform === 'win32', cwd: repoRoot });
    if (again.status !== 0) break; // استعلامٌ فاشل يُترك للبوّابة أدناه: الفشل مُغلِق
    try {
      const parsed = JSON.parse(again.stdout);
      status = parsed.mergeStateStatus ?? null;
      number = parsed.number ?? number;
      headRef = parsed.headRefName ?? headRef;
    } catch {
      status = null;
      break;
    }
  }
  if (status === 'UNKNOWN') {
    console.error(
      [
        `⛔ حالة الطلب #${number} ما زالت **UNKNOWN** بعد ${UNKNOWN_TRIES} محاولاتٍ و${Math.round(waitedMs / 1000)} ثانيةً — والدمج ممنوع (ق-٢٦٠).`,
        '',
        'UNKNOWN = GitHub **لم يفرغ من حساب القابلية** — لا أنها سليمة ولا أنها ساقطة.',
        'ويقع هذا عادةً **بعد دمجٍ سابق** يُبطل الحساب لكل طلبٍ مفتوح.',
        '',
        'والدمجُ عليها دمجٌ **قبل أن يُعرف شيء** — وهو ما بُنيت هذه البوّابة لمنعه.',
        '',
        'الطريق:',
        `  ١. أعد الأمر بعد قليل — أو اقرأ الحالة أولاً:  gh pr view ${prNumber || '<رقم>'} --json mergeStateStatus`,
        '  ٢. فإن بقيت UNKNOWN دقائقَ طويلة، فالمشكلة عند GitHub لا في الطلب.',
      ].join('\n'),
    );
    process.exit(2);
  }

  /**
   * ⛔ **طلبٌ مكدَّسٌ على هذا الفرع يُغلَق تلقائياً بحذفه** (`ق-١٤٤` — وقعت مرتَين:
   * #121 في 2026-08، و#151 في 2026-09-05 بعد أن أُعيد توجيه أخيه #150 **وحدَه**).
   *
   * القاعدة كانت في الذاكرة: «يُعاد توجيه المكدَّس إلى main قبل دمج قاعدته» —
   * وذاكرةٌ تُطبَّق على طلبٍ وتُنسى عن الذي بجواره. فالبوّابة تسأل GitHub: أثمّة
   * طلبٌ مفتوحٌ قاعدتُه فرعُ هذا الطلب؟ إن وُجد **رُفض الدمج بالاسم** حتى يُعاد
   * توجيهه — والحذفُ (`--delete-branch`) ليس شرط الرفض: دمجُ القاعدة بالسحق يقطع
   * أسلافَ المكدَّس فيحمل الموجةَ كلها (`ق-١٤٤`)، حُذف الفرع أو بقي.
   *
   * والفشلُ في هذا الاستعلام **مُغلِق** كسابقه: قائمةٌ لم تُقرأ ليست قائمةً فارغة.
   */
  if (headRef) {
    const stacked = spawnSync('gh', ['pr', 'list', '--state', 'open', '--base', headRef, '--json', 'number,headRefName'], {
      encoding: 'utf8',
      shell: process.platform === 'win32',
      cwd: repoRoot,
    });
    let children = null;
    if (stacked.status === 0) {
      try {
        children = JSON.parse(stacked.stdout);
      } catch {
        children = null;
      }
    }
    if (children === null) {
      console.error(`⛔ تعذّر قراءة الطلبات المكدَّسة على ${headRef} قبل دمج #${number} — والدمج ممنوع بلا قراءتها (الفشل مُغلِق).`);
      process.exit(2);
    }
    if (children.length > 0) {
      const list = children.map((c) => `#${c.number} (${c.headRefName})`).join(' · ');
      console.error(
        [
          `⛔ #${number} قاعدةٌ لطلبٍ مفتوح: ${list} — والدمج ممنوع حتى يُعاد توجيهه (ق-١٤٤).`,
          '',
          'الحادثتان: #121 (2026-08) و#151 (2026-09-05) أُغلقا تلقائياً بحذف قاعدتهما،',
          'والثانية وقعت مع القاعدة في الذاكرة — فصارت بوّابةً.',
          '',
          'الطريق:',
          ...children.map((c) => `  gh pr edit ${c.number} --base main`),
          `  ثم أعد: gh pr merge ${number} …`,
          '  وبعد الدمج: git rebase --onto origin/main <طرف القاعدة القديم> على كل فرعٍ مكدَّس.',
        ].join('\n'),
      );
      process.exit(2);
    }
  }

  if (status === null) {
    console.error(
      [
        `⛔ تعذّر قراءة حالة الطلب #${number} قبل الدمج — والدمج ممنوع بلا قراءتها.`,
        '',
        '**والفشل مُغلِق لا مفتوح عمداً**: حالةٌ لم تُقرأ ليست حالةً سليمة.',
        `تفصيل: ${String(probe.stderr || probe.error?.message || 'مخرَج غير مفهوم').trim().slice(0, 300)}`,
      ].join('\n'),
    );
    process.exit(2);
  }

  /**
   * ⚠️ **«فحوصٌ لم تكتمل» تُرفض كذلك** (قرار المالك 2026-08-16): الدمج قبل
   * اكتمالها دمجٌ **قبل أن يُعرَف شيء**، ويبدو أسلمَ ممّا هو — لأنه لا يُرى
   * أحمرَ فيُقرأ «لم يسقط شيء».
   *
   * 📌 **وقياسٌ صحّح فهمي:** GitHub لا يعطي `PENDING` في هذا المستودع —
   * **يطوي «لم يكتمل» داخل `UNSTABLE` نفسها**. مقروءٌ من `#65` وهو يُدمَج:
   *
   *     mergeStateStatus = UNSTABLE
   *     vitest pass · api-unit pass · nginx-cache pass · playwright pass
   *     db-integration **pending**            ⟵ ولا فحص ساقط إطلاقاً
   *
   * فـ`UNSTABLE` تعني **«لم تنجح كل الفحوص»** لا «سقط فحص». و`PENDING` تبقى
   * في القائمة لأن GitHub يستعملها في إعداداتٍ أخرى — فوجودها احتياطٌ لا زينة.
   */
  if (status === 'UNSTABLE' || status === 'BLOCKED' || status === 'PENDING') {
    console.error(
      [
        `⛔ الطلب #${number} حالته ${status} — والدمج ممنوع.`,
        '',
        'UNSTABLE = **لم تنجح كل الفحوص** — إمّا سقط أحدها وإمّا لم يكتمل بعد.',
        '           ولا تعني بالضرورة وجود أحمر: قد تكون كلها خضراء وواحدٌ يعمل.',
        'PENDING  = فحوصٌ لم تبدأ أو لم تكتمل.',
        'BLOCKED  = مراجعةٌ أو حمايةٌ تمنع.',
        '',
        'الحادثة (2026-08-16): دُمج #61 وحالته UNSTABLE لأن الفحص قُرئ **في نفس',
        'الأمر الذي دمج**، فطُبع ومضى قبل أن يُقرأ. وكانت db-integration ساقطة،',
        'فصارت main حمراء.',
        '',
        'الطريق:',
        `  ١. اقرأ السبب:   gh pr checks ${prNumber || '<رقم>'}`,
        '  ٢. أصلحه، وانتظر اخضرار الفحوص، ثم أعد الأمر.',
        '  ٣. أو بإذن المالك الصريح في رسالته: أضف MERGE_UNSTABLE_OK=1 إلى الأمر.',
      ].join('\n'),
    );
    process.exit(2);
  }

  /**
   * ⛔ **طلبٌ يمسّ شيفرةً ولم يعمل عليه فحصٌ ثقيل قطّ** (`ق-٢٥٤` — يُغلق الثقبَ
   * المعلَن في `ق-٢٥١`).
   *
   * بعد تقسيم السير بالمسار، الثقيلُ يعمل **عند فتح الطلب لما يمسّ شيفرة**
   * وعند الدمج. فطلبٌ يُفتح **وثائقياً** ثم تُدفع فيه **شيفرة** لا يعمل عليه
   * ثقيلٌ قبل الدمج: الفتحُ مضى، و`synchronize` مستثناة من مُشغِّله. والفحوصُ
   * تبدو خضراء — لأن الخفيفَ وحده عمل، **وأخضرُ ناقصٌ يُقرأ أخضرَ تامّاً**.
   *
   * والبوّابة تسأل سؤالين ولا تفترض جواباً:
   *   ① أيمسّ الطلبُ مساراً شيفرياً؟ — **والمسارات تُقرأ من المُشغِّل الثقيل
   *      نفسه** لا من قائمةٍ هنا: قائمةٌ ثانية تفترق عن الأولى يوماً.
   *   ② أفي **أيٍّ من تواريخ الطلب** فحصٌ باسم وظيفةٍ ثقيلة؟ — لا على الرأس
   *      وحده: الثقيلُ يعمل عند الفتح، والرأسُ قد تقدّم بعده بدفعةٍ خفيفة،
   *      وهذا **مقبولٌ بالتصميم** (ق-٢٥١) — المرفوضُ أن **لا يكون عمل قطّ**.
   *
   * حدُّها المعلَن: مطابقةُ المسارات تفهم `x/**` والاسمَ الصريح — وهي كلُّ ما
   * يستعمله المُشغِّل اليوم؛ ونمطٌ أعقد يُقرأ **غيرَ مطابق** فتُرفَض بحقٍّ زائد
   * لا بسماحٍ ناقص. والفشلُ في أي استعلام **مُغلِق** كسابقَيه.
   */
  const heavyFile = resolve(repoRoot, '.github', 'workflows', 'web-tests.yml');
  let heavyPaths = null;
  let heavyJobs = null;
  try {
    const yaml = readFileSync(heavyFile, 'utf8')
      .split(/\r?\n/)
      .filter((l) => !/^\s*#/.test(l))
      .join('\n');
    const pr = yaml.slice(yaml.indexOf('\n  pull_request:') + 1);
    const prBlock = pr.slice(0, pr.slice(1).search(/\n {0,2}\S/) + 1);
    heavyPaths = [...prBlock.matchAll(/^\s{6}- '([^']+)'/gm)].map((m) => m[1]);
    const jobsAt = yaml.indexOf('\njobs:\n');
    heavyJobs = [...yaml.slice(jobsAt).matchAll(/^ {2}([A-Za-z0-9_-]+):\s*$/gm)].map((m) => m[1]);
  } catch {
    heavyPaths = null;
  }
  if (!heavyPaths?.length || !heavyJobs?.length) {
    console.error(`⛔ تعذّرت قراءة مسارات المُشغِّل الثقيل أو وظائفه من ${heavyFile} — والدمج ممنوع بلا قراءتها (الفشل مُغلِق).`);
    process.exit(2);
  }

  const touches = (file) => heavyPaths.some((p) => (p.endsWith('/**') ? file.startsWith(p.slice(0, -2)) : file === p));
  const filesProbe = spawnSync('gh', ['pr', 'view', ...(prNumber ? [prNumber] : []), '--json', 'files,commits'], {
    encoding: 'utf8',
    shell: process.platform === 'win32',
    cwd: repoRoot,
  });
  let prFiles = null;
  let commits = null;
  if (filesProbe.status === 0) {
    try {
      const parsed = JSON.parse(filesProbe.stdout);
      prFiles = (parsed.files ?? []).map((f) => f.path);
      commits = (parsed.commits ?? []).map((c) => c.oid);
    } catch {
      prFiles = null;
    }
  }
  if (prFiles === null || commits === null) {
    console.error(`⛔ تعذّرت قراءة ملفات #${number} أو تواريخه قبل الدمج — والدمج ممنوع بلا قراءتها (الفشل مُغلِق).`);
    process.exit(2);
  }

  const codeFiles = prFiles.filter(touches);
  if (codeFiles.length > 0) {
    let found = null;
    for (const sha of commits.slice(-20)) {
      const runs = spawnSync('gh', ['api', `repos/{owner}/{repo}/commits/${sha}/check-runs`], {
        encoding: 'utf8',
        shell: process.platform === 'win32',
        cwd: repoRoot,
      });
      if (runs.status !== 0) {
        console.error(`⛔ تعذّرت قراءة فحوص ${sha.slice(0, 7)} في #${number} — والدمج ممنوع بلا قراءتها (الفشل مُغلِق).`);
        process.exit(2);
      }
      try {
        const names = (JSON.parse(runs.stdout).check_runs ?? []).map((r) => r.name);
        const hit = names.find((n) => heavyJobs.includes(n));
        if (hit) {
          found = `${hit} على ${sha.slice(0, 7)}`;
          break;
        }
      } catch {
        console.error(`⛔ مخرَجُ فحوص ${sha.slice(0, 7)} غير مفهوم — والدمج ممنوع (الفشل مُغلِق).`);
        process.exit(2);
      }
    }
    if (!found) {
      console.error(
        [
          `⛔ #${number} يمسّ شيفرةً ولم يعمل عليه فحصٌ ثقيل قطّ — والدمج ممنوع (ق-٢٥٤).`,
          '',
          `الملفات الشيفرية: ${codeFiles.slice(0, 5).join(' · ')}${codeFiles.length > 5 ? ` … (+${codeFiles.length - 5})` : ''}`,
          `الوظائف الثقيلة المنتظَرة: ${heavyJobs.join(' · ')}`,
          `فُحص ${commits.length} تاريخاً ولم يُوجد أيٌّ منها.`,
          '',
          'السبب البنيوي: الثقيلُ يعمل عند **فتح** الطلب لما يمسّ شيفرة، ودفعةٌ',
          'لاحقة (synchronize) لا تُشغّله. فطلبٌ فُتح وثائقياً ثم دُفعت فيه شيفرة',
          'يصل الدمجَ بأخضرَ **ناقص**.',
          '',
          'الطريق:',
          `  gh pr close ${prNumber || '<رقم>'} && gh pr reopen ${prNumber || '<رقم>'}   ⟵ إعادةُ الفتح تُشغّل الثقيل`,
          '  ثم انتظر اخضراره وأعد الدمج.',
        ].join('\n'),
      );
      process.exit(2);
    }
  }
}

process.exit(0);
